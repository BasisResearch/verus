//! Export a Verus transition-system model to TLA+.
//!
//! The exporter reads the typed VIR crate, finds the model's `(State, init,
//! next, invariants)` triple, and prints TLA+ operators for every spec
//! function the triple reaches. It keys on nothing from any one project:
//! datatypes become records, `vstd` collections become TLA+ sequences, sets
//! and functions, spec functions become operators, and a quantifier is
//! bounded from its own guard. Whatever it cannot express it refuses with a
//! source location, and whatever it cannot bound becomes a `CONSTANT` the
//! model config must supply. Both lists come back in the [`Report`].
//!
//! Every local name (parameter, `let`, pattern binding, quantifier binder,
//! helper) is fresh within its operator and distinct from every operator,
//! variable and constant, since TLA+ forbids redefining a name in its scope.
//!
//! Three ways of writing a transition system are recognised:
//!
//! * hand-rolled: `init(s: S) -> bool`, `next(pre: S, post: S) -> bool` in
//!   the named module, invariants the module's other `(S) -> bool` spec
//!   functions (one named `invariant` included), except those `init`/`next`
//!   read unprimed, which are guards;
//! * VerusSync: `State::init(post)`, `State::next(pre, post)` generated by
//!   `state_machine!`, invariants the `#[invariant]` methods;
//! * verus-tla: `init()` and `next()` returning `spec_fn` closures over the
//!   state, with `Action { precondition, transition }` records inlined.
//!
//! The state datatype's fields are the TLA+ variables. A parameter of the
//! state type in the pre role prints as the unprimed variables, one in the
//! post role as the primed ones, so `post.f == e` becomes `f' = e`, which is
//! the shape TLC needs to assign a primed variable.

use crate::ast::*;
use crate::ast_util::{fun_as_friendly_rust_name, path_as_friendly_rust_name};
use serde::Serialize;
use std::collections::{BTreeMap, BTreeSet, HashMap, HashSet};
use std::sync::Arc;

/// Something the export could not express; the `.tla` prints
/// `Assert(FALSE, "...")` at the site, so TLC stops wherever it is evaluated,
/// and an invariant that reaches one is left out of the `.cfg`.
#[derive(Debug, Clone, Serialize)]
pub struct Refusal {
    pub what: String,
    pub location: String,
    pub in_function: String,
}

/// A quantifier the export could not bound; the `.cfg` skeleton carries a
/// `CONSTANT` for it.
#[derive(Debug, Clone, Serialize)]
pub struct Hole {
    pub variable: String,
    pub typ: String,
    pub constant: String,
    pub location: String,
    pub in_function: String,
}

/// A candidate invariant (a predicate over one state in the model's module)
/// and what became of it.
#[derive(Debug, Clone, Serialize)]
pub struct Candidate {
    pub function: String,
    /// The operator it is printed as, when it is printed.
    pub operator: Option<String>,
    /// Whether it is an invariant in the `.cfg`.
    pub included: bool,
    pub reason: String,
}

/// A transition: an operator Next reaches through a disjunction, an `IF` or
/// `match` branch, or an `exists`, together with the operators it conjoins,
/// and the variables none of them assigns (a conjunct-level `v' = e`). TLC
/// stops on such a step with "successor state not completely specified"; in
/// Verus the variable is unconstrained.
#[derive(Debug, Clone, Serialize)]
pub struct Transition {
    pub operator: String,
    pub unassigned: Vec<String>,
}

#[derive(Debug, Clone, Serialize)]
pub struct Report {
    pub module: String,
    pub shape: String,
    pub state_type: String,
    pub variables: Vec<String>,
    /// The variables TypeOK keeps in their types' ranges.
    pub typed_variables: Vec<String>,
    pub init: String,
    pub next: String,
    pub invariants: Vec<String>,
    /// Every transition Next reaches, with the variables it leaves unassigned.
    pub transitions: Vec<Transition>,
    /// Invariants left out of the `.cfg` because they reach a refusal.
    pub skipped_invariants: Vec<String>,
    /// Every candidate invariant, included or not, and why.
    pub candidates: Vec<Candidate>,
    pub operators: usize,
    pub holes: Vec<Hole>,
    pub refusals: Vec<Refusal>,
}

pub struct Export {
    /// The TLA+ module's name; the `.tla` must be written as `<module_name>.tla`.
    pub module_name: String,
    pub tla: String,
    pub cfg: String,
    pub report: Report,
}

/// Verus's Euclidean division and remainder (the remainder is never
/// negative), for divisors other than a positive literal. Reserved at module
/// level, so no operator or local takes these names.
const EUCLID_DIV: &str = "EuclidDiv";
const EUCLID_MOD: &str = "EuclidMod";
/// The Euclidean operators' parameters. TLA+ forbids a parameter that
/// redefines a variable or operator, so these are reserved too, and a state
/// field of the same name is held in a renamed variable.
const EUCLID_A: &str = "euclid_a";
const EUCLID_B: &str = "euclid_b";

/// The module-level names the export generates beside the operators.
const GENERATED_NAMES: [&str; 10] =
    ["Init", "Next", "Spec", "vars", "Inv", "TypeOK", EUCLID_DIV, EUCLID_MOD, EUCLID_A, EUCLID_B];

/// How an operator is called, for [`Exporter::transitions`]: at conjunct
/// level inside a branch (a transition of its own), at conjunct level
/// outside any branch (part of its caller's transition), or elsewhere (a
/// guard, an operand: it assigns nothing).
#[derive(Clone, Copy, PartialEq, Eq)]
enum Reach {
    Branch,
    Conjoined,
    Other,
}

/// An operator: a function, and whether it is the variant whose single
/// state parameter is read as the primed variables (a callee given `post`
/// where it declares one state parameter).
type OpKey = (Fun, bool);

#[derive(Clone, Copy, PartialEq, Eq)]
enum Role {
    Pre,
    Post,
}

#[derive(Clone)]
struct Env {
    /// State-typed parameters in a pre or post role.
    roles: HashMap<VarIdent, Role>,
    /// Every other variable in scope, by its printed name.
    names: HashMap<VarIdent, String>,
    /// Variables bound to a closure or record value, kept symbolically so a
    /// later application or field selection can be reduced.
    values: HashMap<VarIdent, (Expr, Box<Env>)>,
}

impl Env {
    fn new() -> Self {
        Env { roles: HashMap::new(), names: HashMap::new(), values: HashMap::new() }
    }
    fn name(&self, v: &VarIdent) -> String {
        self.names.get(v).cloned().unwrap_or_else(|| ident_name(v))
    }
}

struct Exporter {
    datatypes: HashMap<Path, Datatype>,
    functions: HashMap<Fun, Function>,
    state_path: Path,
    /// The state datatype's fields: the record labels, and the TLA+ variable
    /// each is held in (the label, renamed where it would clash with a
    /// generated module-level name or a TLA+ reserved word).
    state_fields: Vec<String>,
    state_vars: Vec<String>,
    /// Whether an operator divides by something other than a positive
    /// literal, so the Euclidean division operators must be emitted.
    uses_euclid: bool,
    /// Operator definitions in dependency order.
    defs: Vec<String>,
    /// Operators already emitted or being emitted (for recursion), keyed by
    /// function and whether it is the primed variant (see [`OpKey`]).
    emitted: HashSet<OpKey>,
    emitting: HashSet<OpKey>,
    /// Recursive operators and their arity, for the `RECURSIVE` declarations.
    recursive: BTreeMap<String, usize>,
    /// Operator name per function, unique.
    op_names: HashMap<OpKey, String>,
    /// Module-level names: operators, state variables, constants.
    used_names: HashSet<String>,
    /// Every local name ever bound, so no operator takes one of them.
    locals_ever: HashSet<String>,
    /// Local names bound so far in the operator being printed. TLA+ forbids
    /// redefining a name inside its own scope, so no local name is reused
    /// within one operator.
    bound: HashSet<String>,
    /// Operators that reach a refusal, directly or through a callee.
    tainted: HashSet<OpKey>,
    /// Whether the operator being printed has reached a refusal so far.
    current_tainted: bool,
    /// How many branches (a disjunct, an `IF` or `match` arm, an `exists`
    /// body, an implication's consequent) enclose the expression being
    /// printed, within its operator.
    branch_depth: usize,
    /// Whether the expression being printed sits at conjunct level of its
    /// operator: reached from the body through conjunctions, `LET`s, the
    /// arms of an `IF`, `match` or disjunction, and `exists` bodies only, so
    /// `v' = e` there assigns `v`.
    conj_level: bool,
    /// The operators each operator calls, and how; the calls of the
    /// operator being printed.
    calls: HashMap<OpKey, Vec<(OpKey, Reach)>>,
    current_calls: Vec<(OpKey, Reach)>,
    /// The state variables each operator's own body assigns (a conjunct-level
    /// `v' = e`, or one every branch of a conjunct-level `IF`, `match` or
    /// disjunction makes); those the operator being printed assigns so far.
    assigned: HashMap<OpKey, BTreeSet<String>>,
    current_assigned: BTreeSet<String>,
    /// What the branches enclosing the one being printed had assigned when
    /// it began, innermost last: TLC has assigned those by the time it
    /// evaluates the branch.
    enclosing_assigned: Vec<BTreeSet<String>>,
    /// The state datatype's field types, in the order of `state_fields`.
    state_types: Vec<Typ>,
    holes: Vec<Hole>,
    refusals: Vec<Refusal>,
    constants: BTreeSet<String>,
    current: String,
}

fn ident_name(v: &VarIdent) -> String {
    let s = v.0.to_string();
    let s: String =
        s.chars().map(|c| if c.is_alphanumeric() || c == '_' { c } else { '_' }).collect();
    let s = if s.is_empty() { "v".to_string() } else { s };
    // TLA+ identifiers cannot start with a digit; a few words are reserved.
    let s = if s.chars().next().map(|c| c.is_ascii_digit()).unwrap_or(false) {
        format!("v{s}")
    } else {
        s
    };
    if is_tla_reserved(&s) { format!("{s}_") } else { s }
}

