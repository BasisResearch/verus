/// Whether a type carries a spec_fn anywhere: such values are reduced
/// symbolically and never printed.
fn typ_has_specfn(
    typ: &Typ,
    datatypes: &HashMap<Path, Datatype>,
    seen: &mut HashSet<Path>,
) -> bool {
    match &**typ {
        TypX::SpecFn(..) | TypX::AnonymousClosure(..) | TypX::FnDef(..) => true,
        TypX::Datatype(Dt::Path(p), args, _) => {
            if args.iter().any(|a| typ_has_specfn(a, datatypes, seen)) {
                return true;
            }
            if !seen.insert(p.clone()) {
                return false;
            }
            datatypes
                .get(p)
                .map(|d| {
                    d.x.variants
                        .iter()
                        .any(|v| v.fields.iter().any(|f| typ_has_specfn(&f.a.0, datatypes, seen)))
                })
                .unwrap_or(false)
        }
        TypX::Datatype(Dt::Tuple(_), args, _) => {
            args.iter().any(|a| typ_has_specfn(a, datatypes, seen))
        }
        TypX::Decorate(_, _, t) | TypX::Boxed(t) => typ_has_specfn(t, datatypes, seen),
        _ => false,
    }
}

impl Exporter {
    fn refuse(&mut self, what: impl Into<String>, span: &crate::messages::Span) -> String {
        let what = what.into();
        self.refusals.push(Refusal {
            what: what.clone(),
            location: span_string(span),
            in_function: self.current.clone(),
        });
        self.current_tainted = true;
        // TLC's `Assert` stops the check with the message wherever the
        // refused expression is evaluated, so a refusal never passes as TRUE.
        let msg = format!("tla-export refused: {what} at {}", span_string(span));
        format!("Assert(FALSE, {})", tla_string(&msg))
    }

    /// Whether a name is taken at module level or reserved by TLA+.
    fn name_taken(&self, n: &str) -> bool {
        self.used_names.contains(n)
            || self.constants.contains(n)
            || self.bound.contains(n)
            || is_tla_reserved(n)
    }

    /// A fresh local name from `base`: never an operator, variable or
    /// constant, and never bound before in the operator being printed.
    fn bind(&mut self, base: &str) -> String {
        let sep = if base.ends_with('_') { "" } else { "_" };
        let mut candidate = base.to_string();
        let mut n = 2;
        while self.name_taken(&candidate) {
            candidate = format!("{base}{sep}{n}");
            n += 1;
        }
        self.bound.insert(candidate.clone());
        self.locals_ever.insert(candidate.clone());
        candidate
    }

    /// A fresh local name for a Verus variable.
    fn bind_var(&mut self, env: &mut Env, v: &VarIdent) -> String {
        let n = self.bind(&ident_name(v));
        env.names.insert(v.clone(), n.clone());
        n
    }

    /// The state's `(label, variable)` pairs.
    fn state_pairs(&self) -> Vec<(String, String)> {
        self.state_fields.iter().cloned().zip(self.state_vars.iter().cloned()).collect()
    }

    /// The TLA+ variable holding the state field `label`.
    fn state_var(&self, label: &str) -> String {
        self.state_pairs()
            .into_iter()
            .find(|(l, _)| l == label)
            .map(|(_, v)| v)
            .unwrap_or_else(|| label.to_string())
    }

    fn is_state_typ(&self, typ: &Typ) -> bool {
        typ_datatype(typ).map(|p| p == self.state_path).unwrap_or(false)
    }

    /// The unique operator name for a function, or for its primed variant.
    fn op_name(&mut self, key: &OpKey) -> String {
        if let Some(n) = self.op_names.get(key) {
            return n.clone();
        }
        let (fun, primed) = key;
        let friendly = fun_as_friendly_rust_name(fun);
        let segs: Vec<&str> = friendly.split("::").collect();
        let mut candidate = ident_name(&VarIdent(
            Arc::new(segs.last().unwrap_or(&"f").to_string()),
            VarIdentDisambiguate::AirLocal,
        ));
        if *primed {
            candidate = format!("{candidate}_post");
        }
        let taken = |this: &Self, c: &str| {
            this.used_names.contains(c)
                || this.locals_ever.contains(c)
                || this.constants.contains(c)
                || is_tla_reserved(c)
        };
        if taken(self, &candidate) && segs.len() >= 2 {
            candidate = format!("{}_{}", sanitize(segs[segs.len() - 2]), candidate);
        }
        let mut n = 2;
        let base = candidate.clone();
        while taken(self, &candidate) {
            candidate = format!("{base}{n}");
            n += 1;
        }
        self.used_names.insert(candidate.clone());
        self.op_names.insert(key.clone(), candidate.clone());
        candidate
    }

    /// The record for a whole state in the given role.
    fn state_record(&self, role: Role) -> String {
        let prime = if role == Role::Post { "'" } else { "" };
        format!(
            "[{}]",
            self.state_pairs()
                .iter()
                .map(|(l, v)| format!("{l} |-> {v}{prime}"))
                .collect::<Vec<_>>()
                .join(", ")
        )
    }

    // ─── expressions ────────────────────────────────────────────────────

    /// Print `e`. Below a node that is not conjunctive (see
    /// [`conjunctive`]) nothing is at conjunct level, so nothing assigns.
    fn expr(&mut self, e: &Expr, env: &Env) -> String {
        let level = self.conj_level;
        if !conjunctive(e) {
            self.conj_level = false;
        }
        let s = self.expr_at(e, env);
        self.conj_level = level;
        s
    }

    /// Run `f` off conjunct level: for a condition, a guard, an operand or
    /// a bound, where `v' = e` does not assign `v`.
    fn quiet<T>(&mut self, f: impl FnOnce(&mut Self) -> T) -> T {
        let level = std::mem::replace(&mut self.conj_level, false);
        let r = f(self);
        self.conj_level = level;
        r
    }

    /// Run `f` for one branch of an `IF`, `match` or disjunction, returning
    /// what it assigns on its own; [`Exporter::meet`] keeps what every branch
    /// assigns.
    fn branch<T>(&mut self, f: impl FnOnce(&mut Self) -> T) -> (T, BTreeSet<String>) {
        let outer = std::mem::take(&mut self.current_assigned);
        self.enclosing_assigned.push(outer);
        let r = f(self);
        let outer = self.enclosing_assigned.pop().expect("pushed above");
        (r, std::mem::replace(&mut self.current_assigned, outer))
    }

    /// Whether the operator being printed has assigned `v` so far, in the
    /// branch being printed or before it.
    fn assigned_so_far(&self, v: &str) -> bool {
        self.current_assigned.contains(v) || self.enclosing_assigned.iter().any(|a| a.contains(v))
    }

    /// A variable is assigned by a branching conjunct when every branch
    /// assigns it.
    fn meet(&mut self, branches: Vec<BTreeSet<String>>) {
        let mut it = branches.into_iter();
        let Some(first) = it.next() else { return };
        let all = it.fold(first, |acc, b| acc.intersection(&b).cloned().collect());
        self.current_assigned.extend(all);
    }

    /// The variable `e` reads as a primed field of the state (`post.f`).
    fn post_field(&self, e: &Expr, env: &Env) -> Option<String> {
        let is_post =
            |v: Option<VarIdent>| v.and_then(|v| env.roles.get(&v).copied()) == Some(Role::Post);
        let is_state = |dt: &Dt| matches!(dt, Dt::Path(p) if *p == self.state_path);
        let e = peel(e);
        match &e.x {
            ExprX::UnaryOpr(UnaryOpr::Field(FieldOpr { datatype, field, .. }), inner)
                if is_state(datatype) && is_post(read_var(inner)) =>
            {
                Some(self.state_var(&field_name(field)))
            }
            ExprX::ReadPlace(p, _) => match &p.x {
                PlaceX::Field(FieldOpr { datatype, field, .. }, inner)
                    if is_state(datatype) && is_post(place_var(inner)) =>
                {
                    Some(self.state_var(&field_name(field)))
                }
                _ => None,
            },
            _ => None,
        }
    }

    /// How `a = b` is printed and the variable it assigns at conjunct level.
    /// TLC assigns `v` only from `v' = e` with `v'` on the left, so a primed
    /// field on the right alone (`pre.y == post.y`) is printed on the left
    /// (`swap`). With a primed field on both sides, the one already assigned
    /// goes on the right and the other is assigned; when neither is, the
    /// equality assigns nothing (TLC cannot evaluate it).
    fn orient(&self, a: &Expr, b: &Expr, env: &Env) -> (bool, Option<String>) {
        match (self.post_field(a, env), self.post_field(b, env)) {
            (Some(x), None) => (false, Some(x)),
            (None, Some(y)) => (true, Some(y)),
            (Some(x), Some(y)) if self.assigned_so_far(&y) => (false, Some(x)),
            (Some(x), Some(y)) if self.assigned_so_far(&x) => (true, Some(y)),
            _ => (false, None),
        }
    }

    /// At conjunct level, the variables `a = b` assigns: every variable when
    /// one side is the whole post state, else the primed field [`Exporter::orient`]
    /// puts on the left.
    fn note_assignment(&mut self, a: &Expr, b: &Expr, env: &Env) {
        if !self.conj_level {
            return;
        }
        let whole =
            |x: &Expr| read_var(x).and_then(|v| env.roles.get(&v).copied()) == Some(Role::Post);
        if whole(a) || whole(b) {
            self.current_assigned.extend(self.state_vars.iter().cloned());
            return;
        }
        if let (_, Some(v)) = self.orient(a, b, env) {
            self.current_assigned.insert(v);
        }
    }

    fn expr_at(&mut self, e: &Expr, env: &Env) -> String {
        match &e.x {
            ExprX::Const(c) => match c {
                Constant::Bool(true) => "TRUE".into(),
                Constant::Bool(false) => "FALSE".into(),
                Constant::Int(i) => i.to_string(),
                Constant::StrSlice(s) => tla_string(s),
                Constant::Real(r) => r.clone(),
                Constant::ByteStr(_) => self.refuse("byte string literal", &e.span),
                Constant::Char(c) => tla_string(&c.to_string()),
                Constant::Float32(_) | Constant::Float64(_) => {
                    self.refuse("float literal", &e.span)
                }
            },
            ExprX::Var(v) => {
                if let Some(role) = env.roles.get(v) {
                    self.state_record(*role)
                } else {
                    env.name(v)
                }
            }
            ExprX::VarAt(..) => self.refuse("old(...) reference", &e.span),
            ExprX::ConstVar(fun, _) | ExprX::StaticVar(fun) => {
                self.ensure_function(&(fun.clone(), false))
            }
            ExprX::ReadPlace(place, _) => self.place(place, env),
            ExprX::Call { target, args, .. } => self.call(e, target, args, env),
            ExprX::Ctor(dt, variant, binders, tail) => {
                self.ctor(e, dt, variant, binders, tail, env)
            }
            ExprX::NullaryOpr(_) => self.refuse("nullary operator", &e.span),
            ExprX::Unary(op, inner) => match op {
                UnaryOp::Not => format!("~({})", self.expr(inner, env)),
                UnaryOp::Trigger(_) | UnaryOp::CoerceMode { .. } => self.expr(inner, env),
                // A clip to `int` is the identity. Any other clip (`as u8`,
                // `as nat`, ...) is only known to land in its range, a fact
                // Verus proves and TLC cannot see: printed as the identity it
                // would give values outside the type, and a check that
                // stopped there would turn the proof-time fact into a
                // runtime failure. Only a literal already in range is kept.
                UnaryOp::Clip { range: IntRange::Int, .. } => self.expr(inner, env),
                UnaryOp::Clip { range, .. } => match &peel(inner).x {
                    ExprX::Const(Constant::Int(i)) if int_in_range(i, range) => i.to_string(),
                    _ => {
                        let what = format!(
                            "cast to {} (TLC cannot keep the value in range)",
                            crate::ast_util::int_range_to_type_string(range)
                        );
                        self.refuse(what, &e.span)
                    }
                },
                UnaryOp::IntToReal | UnaryOp::RealToInt => self.expr(inner, env),
                _ => {
                    let what = format!("unary operator {:?}", op);
                    self.refuse(what, &e.span)
                }
            },
            ExprX::UnaryOpr(op, inner) => match op {
                UnaryOpr::Box(_) | UnaryOpr::Unbox(_) => self.expr(inner, env),
                UnaryOpr::HasType(_) => "TRUE".into(),
                UnaryOpr::IsVariant { datatype, variant } => {
                    let inner_s = self.expr(inner, env);
                    if self.single_variant(datatype) {
                        "TRUE".into()
                    } else {
                        format!("({inner_s}.tag = \"{variant}\")")
                    }
                }
                UnaryOpr::Field(FieldOpr { datatype, field, .. }) => {
                    if let Some(v) = read_var(inner) {
                        if let Some(role) = env.roles.get(&v) {
                            if matches!(datatype, Dt::Path(p) if *p == self.state_path) {
                                let prime = if *role == Role::Post { "'" } else { "" };
                                return format!("{}{prime}", self.state_var(&field_name(field)));
                            }
                        }
                    }
                    let inner_s = self.expr(inner, env);
                    self.field_access(&inner_s, datatype, field)
                }
                UnaryOpr::IntegerTypeBound(..) => self.refuse("integer type bound", &e.span),
                UnaryOpr::ProofNote(_) | UnaryOpr::CustomErr(_) => self.expr(inner, env),
                _ => {
                    let what = format!("unary operator {:?}", op);
                    self.refuse(what, &e.span)
                }
            },
            ExprX::Logical(op, a, b) => {
                let (sa, sb) = match op {
                    LogicalOp::And => (self.expr(a, env), self.expr(b, env)),
                    LogicalOp::Or => {
                        let (sa, aa) = self.branch(|x| x.in_branch(a, env));
                        let (sb, ab) = self.branch(|x| x.in_branch(b, env));
                        self.meet(vec![aa, ab]);
                        (sa, sb)
                    }
                    LogicalOp::Implies => (self.expr(a, env), self.in_branch(b, env)),
                };
                let sym = match op {
                    LogicalOp::And => "/\\",
                    LogicalOp::Or => "\\/",
                    LogicalOp::Implies => "=>",
                };
                format!("({sa} {sym} {sb})")
            }
            ExprX::Binary(op, a, b) => self.binary(e, op, a, b, env),
            ExprX::BinaryOpr(BinaryOpr::ExtEq(..), a, b) => {
                let (a, b) = if self.orient(a, b, env).0 { (b, a) } else { (a, b) };
                self.note_assignment(a, b, env);
                self.quiet(|x| format!("({} = {})", x.expr(a, env), x.expr(b, env)))
            }
            ExprX::Multi(MultiOp::Chained(ops), args) => {
                let mut parts = Vec::new();
                for (i, op) in ops.iter().enumerate() {
                    let l = self.expr(&args[i], env);
                    let r = self.expr(&args[i + 1], env);
                    let sym = match op {
                        ChainedOp::Inequality(InequalityOp::Le) => "<=",
                        ChainedOp::Inequality(InequalityOp::Lt) => "<",
                        ChainedOp::Inequality(InequalityOp::Ge) => ">=",
                        ChainedOp::Inequality(InequalityOp::Gt) => ">",
                        ChainedOp::MultiEq => "=",
                    };
                    parts.push(format!("({l} {sym} {r})"));
                }
                format!("({})", parts.join(" /\\ "))
            }
            ExprX::Quant(q, binders, body) => self.quant(e, q, binders, body, env),
            ExprX::Closure(..) => self.refuse("closure outside a known call", &e.span),
            ExprX::Choose { .. } => self.refuse("choose (TLC cannot evaluate it)", &e.span),
            ExprX::WithTriggers { body, .. } => self.expr(body, env),
            ExprX::If(c, t, f) => {
                let sc = self.quiet(|x| x.expr(c, env));
                let (st, at) = self.branch(|x| x.in_branch(t, env));
                let (sf, af) = match f {
                    Some(f) => self.branch(|x| x.in_branch(f, env)),
                    None => ("TRUE".into(), BTreeSet::new()),
                };
                self.meet(vec![at, af]);
                format!("(IF {sc} THEN {st} ELSE {sf})")
            }
            ExprX::Match(place, arms, _) => self.matches(e, place, arms, env),
            ExprX::Block(stmts, tail) => self.block(e, stmts, tail, env),
            ExprX::Header(_)
            | ExprX::Fuel(..)
            | ExprX::RevealString(_)
            | ExprX::RevealByteString(_) => "TRUE".into(),
            ExprX::AssertAssume { .. } | ExprX::AssertBy { .. } | ExprX::AssertQuery { .. } => {
                "TRUE".into()
            }
            _ => {
                let what = format!("expression kind {}", expr_kind(&e.x));
                self.refuse(what, &e.span)
            }
        }
    }

    fn binary(&mut self, e: &Expr, op: &BinaryOp, a: &Expr, b: &Expr, env: &Env) -> String {
        match op {
            BinaryOp::Eq(_) | BinaryOp::Ne => {
                let sym = if matches!(op, BinaryOp::Eq(_)) { "=" } else { "#" };
                // The primed field TLC assigns goes on the left.
                let (a, b) = if self.orient(a, b, env).0 { (b, a) } else { (a, b) };
                if sym == "=" {
                    self.note_assignment(a, b, env);
                }
                self.quiet(|x| {
                    // Whole-state equality with the post state on one side:
                    // one primed assignment per field, so TLC can enumerate.
                    if let Some(assign) = x.state_assignment(a, b, env) {
                        return if sym == "=" { assign } else { format!("~({assign})") };
                    }
                    format!("({} {sym} {})", x.expr(a, env), x.expr(b, env))
                })
            }
            BinaryOp::Inequality(iq) => {
                let sym = match iq {
                    InequalityOp::Le => "<=",
                    InequalityOp::Ge => ">=",
                    InequalityOp::Lt => "<",
                    InequalityOp::Gt => ">",
                };
                format!("({} {sym} {})", self.expr(a, env), self.expr(b, env))
            }
            BinaryOp::Arith(ar) => {
                let sym = match ar {
                    ArithOp::Add(_) => "+",
                    ArithOp::Sub(_) => "-",
                    ArithOp::Mul(_) => "*",
                    ArithOp::EuclideanDiv(_) | ArithOp::EuclideanMod(_) => {
                        // TLA+'s `\div` rounds down and TLC's `%` wants a
                        // positive divisor; both agree with Verus's
                        // Euclidean operators only when the divisor is
                        // positive, so any other divisor goes through
                        // `EuclidDiv`/`EuclidMod`.
                        let div = matches!(ar, ArithOp::EuclideanDiv(_));
                        let (sa, sb) = (self.expr(a, env), self.expr(b, env));
                        let positive = matches!(&peel(b).x,
                            ExprX::Const(Constant::Int(i)) if i > &num_bigint::BigInt::from(0));
                        if positive {
                            let sym = if div { "\\div" } else { "%" };
                            return format!("({sa} {sym} {sb})");
                        }
                        self.uses_euclid = true;
                        let op = if div { EUCLID_DIV } else { EUCLID_MOD };
                        return format!("{op}({sa}, {sb})");
                    }
                };
                format!("({} {sym} {})", self.expr(a, env), self.expr(b, env))
            }
            BinaryOp::Xor => format!("({} # {})", self.expr(a, env), self.expr(b, env)),
            BinaryOp::Index(..) => {
                // Array or slice indexing: 0-based in Verus, 1-based here.
                format!("{}[({}) + 1]", self.expr(a, env), self.expr(b, env))
            }
            _ => {
                let what = format!("binary operator {:?}", op);
                self.refuse(what, &e.span)
            }
        }
    }

    /// `post == e` (either side) on the whole state, as per-field primed
    /// assignments; `pre == e` likewise unprimed.
    fn state_assignment(&mut self, a: &Expr, b: &Expr, env: &Env) -> Option<String> {
        let role_of = |x: &Expr| read_var(x).and_then(|v| env.roles.get(&v).copied());
        let (role, other) = match (role_of(a), role_of(b)) {
            (Some(r), None) => (r, b),
            (None, Some(r)) => (r, a),
            (Some(Role::Post), Some(Role::Pre)) | (Some(Role::Pre), Some(Role::Post)) => {
                let vars = self.state_vars.clone();
                return Some(format!(
                    "({})",
                    vars.iter().map(|v| format!("{v}' = {v}")).collect::<Vec<_>>().join(" /\\ ")
                ));
            }
            _ => return None,
        };
        let prime = if role == Role::Post { "'" } else { "" };
        let fields = self.state_pairs();
        // A constructor of the state type assigns field by field; anything
        // else is projected.
        if let ExprX::Ctor(Dt::Path(p), _variant, binders, tail) = &other.x {
            if *p == self.state_path {
                let mut parts = Vec::new();
                for (f, var) in &fields {
                    let given = binders.iter().find(|b| field_name(&b.name) == *f);
                    let value = match given {
                        Some(b) => self.expr(&b.a, env),
                        None => match tail {
                            Some(t) => {
                                let base = self.place(&t.place, env);
                                format!("{base}.{f}")
                            }
                            None => self.refuse("state constructor without the field", &other.span),
                        },
                    };
                    parts.push(format!("{var}{prime} = {value}"));
                }
                return Some(format!("({})", parts.join(" /\\ ")));
            }
        }
        let so = self.expr(other, env);
        let s = self.bind("s__");
        Some(format!(
            "(LET {s} == {so} IN {})",
            fields
                .iter()
                .map(|(f, var)| format!("{var}{prime} = {s}.{f}"))
                .collect::<Vec<_>>()
                .join(" /\\ ")
        ))
    }

    fn single_variant(&self, dt: &Dt) -> bool {
        match dt {
            Dt::Path(p) => self.datatypes.get(p).map(|d| d.x.variants.len() == 1).unwrap_or(false),
            Dt::Tuple(_) => true,
        }
    }

    fn field_access(&mut self, base: &str, dt: &Dt, field: &Ident) -> String {
        match dt {
            Dt::Tuple(_) => {
                let idx: usize = field.parse().unwrap_or(0);
                format!("{base}[{}]", idx + 1)
            }
            Dt::Path(_) => format!("{base}.{}", field_name(field)),
        }
    }

    fn ctor(
        &mut self,
        e: &Expr,
        dt: &Dt,
        variant: &Ident,
        binders: &Binders<Expr>,
        tail: &Option<CtorUpdateTail>,
        env: &Env,
    ) -> String {
        match dt {
            Dt::Tuple(_) => {
                let mut items: Vec<(usize, String)> = binders
                    .iter()
                    .map(|b| (b.name.parse::<usize>().unwrap_or(0), self.expr(&b.a, env)))
                    .collect();
                items.sort_by_key(|(i, _)| *i);
                format!("<<{}>>", items.into_iter().map(|(_, s)| s).collect::<Vec<_>>().join(", "))
            }
            Dt::Path(p) => {
                let tagged = !self.single_variant(dt);
                if let Some(t) = tail {
                    let base = self.place(&t.place, env);
                    if binders.is_empty() {
                        return base;
                    }
                    let updates: Vec<String> = binders
                        .iter()
                        .map(|b| format!("!.{} = {}", field_name(&b.name), self.expr(&b.a, env)))
                        .collect();
                    return format!("[{base} EXCEPT {}]", updates.join(", "));
                }
                let mut fields: Vec<String> = Vec::new();
                if tagged {
                    fields.push(format!("tag |-> \"{variant}\""));
                }
                // Keep declaration order.
                let declared: Vec<Ident> = self
                    .datatypes
                    .get(p)
                    .and_then(|d| {
                        d.x.variants
                            .iter()
                            .find(|v| &v.name == variant)
                            .map(|v| v.fields.iter().map(|f| f.name.clone()).collect())
                    })
                    .unwrap_or_else(|| binders.iter().map(|b| b.name.clone()).collect());
                for name in declared {
                    if let Some(b) = binders.iter().find(|b| b.name == name) {
                        fields.push(format!("{} |-> {}", field_name(&name), self.expr(&b.a, env)));
                    }
                }
                if fields.is_empty() {
                    let _ = e;
                    "[tag |-> \"unit\"]".to_string()
                } else {
                    format!("[{}]", fields.join(", "))
                }
            }
        }
    }

    fn place(&mut self, p: &Place, env: &Env) -> String {
        match &p.x {
            PlaceX::Local(v) => {
                if let Some(role) = env.roles.get(v) {
                    self.state_record(*role)
                } else {
                    env.name(v)
                }
            }
            PlaceX::Field(FieldOpr { datatype, field, .. }, inner) => {
                if let Some(v) = place_var(inner) {
                    if let Some(role) = env.roles.get(&v) {
                        if matches!(datatype, Dt::Path(p) if *p == self.state_path) {
                            let prime = if *role == Role::Post { "'" } else { "" };
                            return format!("{}{prime}", self.state_var(&field_name(field)));
                        }
                    }
                }
                let base = self.place(inner, env);
                self.field_access(&base, datatype, field)
            }
            PlaceX::Temporary(e) | PlaceX::WithExpr(e, _) => self.expr(e, env),
            PlaceX::DerefMut(inner) | PlaceX::ModeUnwrap(inner, _) => self.place(inner, env),
            PlaceX::Index(inner, idx, _, _) => {
                format!("{}[({}) + 1]", self.place(inner, env), self.expr(idx, env))
            }
            PlaceX::UserDefinedTypInvariantObligation(inner, _) => self.place(inner, env),
        }
    }

    fn block(&mut self, e: &Expr, stmts: &Stmts, tail: &Option<Expr>, env: &Env) -> String {
        let mut env2 = env.clone();
        let mut lets = Vec::new();
        for s in stmts.iter() {
            match &s.x {
                StmtX::Decl { pattern, init: Some(init), .. } => match &pattern.x {
                    PatternX::Var(PatternBinding { name, .. }) => {
                        let symbolic = match &init.x {
                            PlaceX::Temporary(e) | PlaceX::WithExpr(e, _) => Some(peel(e)),
                            _ => None,
                        };
                        // A closure or a record of closures is kept only
                        // symbolically, for a later application to reduce.
                        let closure_valued =
                            typ_has_specfn(&pattern.typ, &self.datatypes, &mut HashSet::new());
                        if closure_valued {
                            if let Some(v) = symbolic {
                                env2.values.insert(name.clone(), (v, Box::new(env2.clone())));
                                continue;
                            }
                        }
                        // The value is read in the scope before the binding,
                        // so `let x = x + 1` reads the outer `x`.
                        let value = self.quiet(|x| x.place(init, &env2));
                        let before = env2.clone();
                        let n = self.bind_var(&mut env2, name);
                        if let Some(v) = symbolic {
                            env2.values.insert(name.clone(), (v, Box::new(before)));
                        }
                        lets.push(format!("{n} == {value}"));
                    }
                    PatternX::Wildcard(_) => {}
                    _ => {
                        let r = self.refuse("destructuring let", &s.span);
                        let n = self.bind("unused__");
                        lets.push(format!("{n} == {r}"));
                    }
                },
                StmtX::Decl { init: None, .. } => {}
                // A proof-mode statement in a spec body: nothing to print.
                StmtX::Expr(_) => {}
            }
        }
        let body = match tail {
            Some(t) => self.expr(t, &env2),
            None => "TRUE".into(),
        };
        let _ = e;
        if lets.is_empty() { body } else { format!("(LET {} IN {body})", lets.join("\n         ")) }
    }

    fn matches(&mut self, e: &Expr, place: &Place, arms: &Arms, env: &Env) -> String {
        let scrutinee = self.quiet(|x| x.place(place, env));
        // Bind the scrutinee once, under a name fresh in this operator.
        let m = self.bind("m__");
        let mut chain: Vec<(String, String)> = Vec::new();
        let mut otherwise: Option<String> = None;
        let mut arm_assigned = Vec::new();
        for arm in arms.iter() {
            let mut env2 = env.clone();
            let (cond, lets) = self.pattern(&m, &arm.x.pattern, &mut env2);
            let in_lets = |x: String| {
                if lets.is_empty() { x } else { format!("(LET {} IN {x})", lets.join(" ")) }
            };
            // The guard reads the pattern's bindings, so it is evaluated
            // inside them (after the pattern's own condition holds).
            let guard = if matches!(arm.x.guard.x, ExprX::Const(Constant::Bool(true))) {
                None
            } else {
                Some(in_lets(self.quiet(|x| x.expr(&arm.x.guard, &env2))))
            };
            let (body, assigned) = self.branch(|x| x.in_branch(&arm.x.body, &env2));
            arm_assigned.push(assigned);
            let body = in_lets(body);
            let cond = match (cond, guard) {
                (None, None) => None,
                (Some(c), None) => Some(c),
                (None, Some(g)) => Some(g),
                (Some(c), Some(g)) => Some(format!("({c} /\\ {g})")),
            };
            match cond {
                Some(c) => chain.push((c, body)),
                None => {
                    otherwise = Some(body);
                    break;
                }
            }
        }
        self.meet(arm_assigned);
        // Verus checks that a match is exhaustive, so this branch is never
        // taken; it is not a refusal.
        let mut tail = otherwise
            .unwrap_or_else(|| "Assert(FALSE, \"tla-export: no match arm applies\")".into());
        let _ = e;
        for (c, b) in chain.into_iter().rev() {
            tail = format!("IF {c} THEN {b} ELSE {tail}");
        }
        format!("(LET {m} == {scrutinee} IN {tail})")
    }

    /// The condition a pattern imposes on `subject`, and the LET bindings it
    /// introduces (added to `env`). The condition reads only `subject`.
    fn pattern(
        &mut self,
        subject: &str,
        p: &Pattern,
        env: &mut Env,
    ) -> (Option<String>, Vec<String>) {
        match &p.x {
            PatternX::Wildcard(_) => (None, vec![]),
            PatternX::Var(PatternBinding { name, .. }) => {
                let n = self.bind_var(env, name);
                (None, vec![format!("{n} == {subject}")])
            }
            PatternX::Binding { binding: PatternBinding { name, .. }, sub_pat } => {
                let n = self.bind_var(env, name);
                let (c, mut lets) = self.pattern(subject, sub_pat, env);
                lets.insert(0, format!("{n} == {subject}"));
                (c, lets)
            }
            PatternX::Constructor(dt, variant, binders) => {
                let mut conds = Vec::new();
                if !self.single_variant(dt) {
                    conds.push(format!("({subject}.tag = \"{variant}\")"));
                }
                let mut lets = Vec::new();
                for b in binders.iter() {
                    let field = self.field_access(subject, dt, &b.name);
                    let (c, l) = self.pattern(&field, &b.a, env);
                    if let Some(c) = c {
                        conds.push(c);
                    }
                    lets.extend(l);
                }
                (if conds.is_empty() { None } else { Some(conds.join(" /\\ ")) }, lets)
            }
            PatternX::Or(..) => {
                let r = self.refuse("or-pattern", &p.span);
                (Some(r), vec![])
            }
            _ => {
                let r = self.refuse("pattern kind", &p.span);
                (Some(r), vec![])
            }
        }
    }

    // ─── calls ──────────────────────────────────────────────────────────

    fn call(&mut self, e: &Expr, target: &CallTarget, args: &Exprs, env: &Env) -> String {
        match target {
            CallTarget::Fun(kind, fun, _typs, _, _) => {
                // The arguments are operands; only the call itself is at the
                // caller's level (restored for `ensure_function` below).
                let level = std::mem::replace(&mut self.conj_level, false);
                let friendly = fun_as_friendly_rust_name(fun);
                if let Some(op) = vstd_op(&friendly) {
                    return self.vstd_call(e, op, args, env);
                }
                // Option's spec helpers, recognised by the receiver's type so
                // a crate function of the same name is left alone.
                let on_option = args
                    .first()
                    .and_then(|a| typ_datatype(&a.typ))
                    .map(|p| path_as_friendly_rust_name(&p) == "core::option::Option")
                    .unwrap_or(false);
                let method = friendly.rsplit("::").next().unwrap_or("");
                if on_option {
                    match method {
                        "is_some" | "is_Some" => {
                            return format!("({}.tag = \"Some\")", self.expr(&args[0], env));
                        }
                        "is_none" | "is_None" => {
                            return format!("({}.tag = \"None\")", self.expr(&args[0], env));
                        }
                        // `.unwrap()` in spec code is vstd's `spec_unwrap`,
                        // whose body is the uninterpreted trait method
                        // `arrow_0`.
                        "unwrap" | "get_Some_0" | "arrow_Some_0" | "arrow_0" | "spec_unwrap"
                        | "spec_expect" => {
                            return format!("{}.v0", self.expr(&args[0], env));
                        }
                        "spec_unwrap_or" if args.len() == 2 => {
                            let (o, d) = (self.expr(&args[0], env), self.expr(&args[1], env));
                            let m = self.bind("o__");
                            return format!(
                                "(LET {m} == {o} IN IF {m}.tag = \"Some\" THEN {m}.v0 ELSE {d})"
                            );
                        }
                        _ => {}
                    }
                }
                let fun = &self.resolved_fun(kind, fun);
                let Some(callee) = self.functions.get(fun).cloned() else {
                    let what = format!("call to {friendly} (no definition in the crate)");
                    return self.refuse(what, &e.span);
                };
                // A state-typed argument passed to a state-role parameter of
                // the callee is dropped. When the callee's single state
                // parameter receives `post`, the call is to the callee's
                // primed variant, which reads that parameter as the primed
                // variables and leaves the other arguments as they are.
                let roles = self.param_roles(&callee);
                let single_state = roles.iter().filter(|r| r.is_some()).count() == 1;
                let mut printed = Vec::new();
                let mut primed = false;
                for (i, a) in args.iter().enumerate() {
                    let arg_role = read_var(a).and_then(|v| env.roles.get(&v).copied());
                    match roles.get(i).copied().flatten() {
                        Some(Role::Pre) => match arg_role {
                            Some(Role::Pre) => {}
                            Some(Role::Post) if single_state => primed = true,
                            Some(Role::Post) => {
                                let r = self.refuse(
                                    "post state passed where the callee expects its pre state",
                                    &a.span,
                                );
                                printed.push(r);
                            }
                            None => {
                                let r = self
                                    .refuse("a computed state passed to a state operator", &a.span);
                                printed.push(r);
                            }
                        },
                        Some(Role::Post) => {
                            if arg_role != Some(Role::Post) {
                                let r = self.refuse("something other than the post state passed as a callee's post state", &a.span);
                                printed.push(r);
                            }
                        }
                        None => printed.push(self.expr(a, env)),
                    }
                }
                self.conj_level = level;
                let name = self.ensure_function(&(fun.clone(), primed));
                if printed.is_empty() { name } else { format!("{name}({})", printed.join(", ")) }
            }
            CallTarget::FnSpec(f) => {
                // The application is reduced: the closure's body sits where
                // the application does, and the arguments are operands.
                let closure = self.quiet(|x| {
                    let (params, body, mut env2, mut lets) = x.resolve_closure(f, env, 0)?;
                    let bindings = params.iter().map(|p| (p.name.clone(), p.a.clone()));
                    x.bind_args(bindings, args, env, &mut env2, &mut lets);
                    Some((body, env2, lets))
                });
                if let Some((body, env2, lets)) = closure {
                    let b = self.expr(&body, &env2);
                    return if lets.is_empty() {
                        b
                    } else {
                        format!("(LET {} IN {b})", lets.join(" "))
                    };
                }
                self.refuse(
                    "application of a spec_fn value that does not reduce to a closure",
                    &e.span,
                )
            }
            CallTarget::BuiltinSpecFun(..) => self.refuse("call_requires/call_ensures", &e.span),
            CallTarget::AssumeExternal => self.refuse("external call", &e.span),
        }
    }

    /// The function a call runs: a trait method call that Verus resolved to
    /// an impl (or a default method) runs that function, which has the body
    /// the trait's declaration lacks.
    fn resolved_fun(&self, kind: &CallTargetKind, fun: &Fun) -> Fun {
        if let CallTargetKind::DynamicResolved { resolved, .. } = kind {
            if self.functions.get(resolved).is_some_and(|f| f.x.body.is_some()) {
                return resolved.clone();
            }
        }
        fun.clone()
    }

    /// Bind parameters to the arguments of an application that is reduced
    /// rather than called: the pre or post state gives the parameter that
    /// role (whatever its declared type: a generic `State` in verus-tla's
    /// Action), a closure-valued argument is kept symbolically, and anything
    /// else becomes a LET binding under a fresh name. The arguments are read
    /// in `env`, the scope of the application.
    fn bind_args(
        &mut self,
        params: impl Iterator<Item = (VarIdent, Typ)>,
        args: &Exprs,
        env: &Env,
        env2: &mut Env,
        lets: &mut Vec<String>,
    ) {
        for ((name, typ), a) in params.zip(args.iter()) {
            if let Some(role) = read_var(a).and_then(|v| env.roles.get(&v).copied()) {
                env2.roles.insert(name.clone(), role);
                continue;
            }
            env2.roles.remove(&name);
            env2.values.insert(name.clone(), (peel(a), Box::new(env.clone())));
            if !typ_has_specfn(&typ, &self.datatypes, &mut HashSet::new()) {
                let value = self.expr(a, env);
                let n = self.bind_var(env2, &name);
                lets.push(format!("{n} == {value}"));
            }
        }
    }

    /// Reduce an expression to a closure literal: a literal, a variable bound
    /// to one, a field of a record bound to one, or a call whose body is
    /// one (its parameters become LET bindings or symbolic values). Returns
    /// the closure's parameters and body with the environment to print the
    /// body in, plus the LET bindings that environment relies on.
    fn resolve_closure(
        &mut self,
        f: &Expr,
        env: &Env,
        depth: usize,
    ) -> Option<(VarBinders<Typ>, Expr, Env, Vec<String>)> {
        if depth > 16 {
            return None;
        }
        let f = peel(f);
        match &f.x {
            ExprX::Closure(params, body) => {
                Some((params.clone(), body.clone(), env.clone(), vec![]))
            }
            ExprX::Var(v) => {
                let (value, venv) = env.values.get(v)?.clone();
                self.resolve_closure(&value, &venv, depth + 1)
            }
            ExprX::ReadPlace(p, _) => self.resolve_place_closure(p, env, depth + 1),
            ExprX::UnaryOpr(UnaryOpr::Field(FieldOpr { field, .. }), inner) => {
                let (record, renv, mut lets) = self.resolve_record(inner, env, depth + 1)?;
                self.closure_of_field(&record, field, renv, &mut lets, depth)
            }
            ExprX::Call { target: CallTarget::Fun(kind, fun, ..), args, .. } => {
                let fun = &self.resolved_fun(kind, fun);
                let (body, env2, mut lets) = self.inline_call(fun, args, env)?;
                let (params, cbody, cenv, mut clets) =
                    self.resolve_closure(&body, &env2, depth + 1)?;
                lets.append(&mut clets);
                Some((params, cbody, cenv, lets))
            }
            _ => None,
        }
    }

    /// The closure in a field of a record constructor.
    fn closure_of_field(
        &mut self,
        record: &Expr,
        field: &Ident,
        renv: Env,
        lets: &mut Vec<String>,
        depth: usize,
    ) -> Option<(VarBinders<Typ>, Expr, Env, Vec<String>)> {
        if let ExprX::Ctor(_, _, binders, _) = &record.x {
            let b = binders.iter().find(|b| &b.name == field)?;
            let (params, body, cenv, mut clets) = self.resolve_closure(&b.a, &renv, depth + 1)?;
            lets.append(&mut clets);
            return Some((params, body, cenv, std::mem::take(lets)));
        }
        None
    }

    /// A call to a crate function with a body, reduced rather than called:
    /// its body, the environment binding its parameters to the arguments,
    /// and the LET bindings that environment relies on.
    fn inline_call(
        &mut self,
        fun: &Fun,
        args: &Exprs,
        env: &Env,
    ) -> Option<(Expr, Env, Vec<String>)> {
        let callee = self.functions.get(fun).cloned()?;
        let body = callee.x.body.clone()?;
        let mut env2 = Env::new();
        let mut lets = Vec::new();
        let params = callee.x.params.iter().map(|p| (p.x.name.clone(), p.x.typ.clone()));
        self.bind_args(params, args, env, &mut env2, &mut lets);
        Some((body, env2, lets))
    }

    fn resolve_place_closure(
        &mut self,
        p: &Place,
        env: &Env,
        depth: usize,
    ) -> Option<(VarBinders<Typ>, Expr, Env, Vec<String>)> {
        match &p.x {
            PlaceX::Local(v) => {
                let (value, venv) = env.values.get(v)?.clone();
                self.resolve_closure(&value, &venv, depth + 1)
            }
            PlaceX::Field(FieldOpr { field, .. }, inner) => {
                let (record, renv, mut lets) = self.resolve_record_place(inner, env, depth + 1)?;
                self.closure_of_field(&record, field, renv, &mut lets, depth)
            }
            PlaceX::Temporary(e) | PlaceX::WithExpr(e, _) => {
                self.resolve_closure(e, env, depth + 1)
            }
            PlaceX::DerefMut(inner) | PlaceX::ModeUnwrap(inner, _) => {
                self.resolve_place_closure(inner, env, depth + 1)
            }
            _ => None,
        }
    }

    /// Reduce an expression to a record constructor, through variables and
    /// calls whose body is one; with the environment to read its fields in
    /// and the LET bindings that environment relies on.
    fn resolve_record(
        &mut self,
        e: &Expr,
        env: &Env,
        depth: usize,
    ) -> Option<(Expr, Env, Vec<String>)> {
        if depth > 16 {
            return None;
        }
        let e = peel(e);
        match &e.x {
            ExprX::Ctor(..) => Some((e.clone(), env.clone(), vec![])),
            ExprX::Var(v) => {
                let (value, venv) = env.values.get(v)?.clone();
                self.resolve_record(&value, &venv, depth + 1)
            }
            ExprX::ReadPlace(p, _) => self.resolve_record_place(p, env, depth + 1),
            ExprX::Call { target: CallTarget::Fun(kind, fun, ..), args, .. } => {
                let fun = &self.resolved_fun(kind, fun);
                let (body, env2, mut lets) = self.inline_call(fun, args, env)?;
                let (record, renv, mut rlets) = self.resolve_record(&body, &env2, depth + 1)?;
                lets.append(&mut rlets);
                Some((record, renv, lets))
            }
            _ => None,
        }
    }

    fn resolve_record_place(
        &mut self,
        p: &Place,
        env: &Env,
        depth: usize,
    ) -> Option<(Expr, Env, Vec<String>)> {
        match &p.x {
            PlaceX::Local(v) => {
                let (value, venv) = env.values.get(v)?.clone();
                self.resolve_record(&value, &venv, depth + 1)
            }
            PlaceX::Temporary(e) | PlaceX::WithExpr(e, _) => self.resolve_record(e, env, depth + 1),
            PlaceX::DerefMut(inner) | PlaceX::ModeUnwrap(inner, _) => {
                self.resolve_record_place(inner, env, depth + 1)
            }
            _ => None,
        }
    }

    /// The `i`th argument of a call, printed; a missing one is refused.
    fn arg(&mut self, e: &Expr, args: &Exprs, i: usize, env: &Env) -> String {
        match args.get(i) {
            Some(a) => self.expr(a, env),
            None => self.refuse("vstd operation with too few arguments", &e.span),
        }
    }

    fn vstd_call(&mut self, e: &Expr, op: &str, args: &Exprs, env: &Env) -> String {
        // Arguments are printed only where an operation uses them, so a
        // closure argument (Seq::new's) is never printed as an expression.
        macro_rules! g {
            ($i:expr) => {
                self.arg(e, args, $i, env)
            };
        }
        match op {
            "seq_len" => format!("Len({})", g!(0)),
            "seq_index" => format!("{}[({}) + 1]", g!(0), g!(1)),
            "seq_push" => format!("Append({}, {})", g!(0), g!(1)),
            "seq_update" => format!("[{} EXCEPT ![({}) + 1] = {}]", g!(0), g!(1), g!(2)),
            "seq_subrange" => format!("SubSeq({}, ({}) + 1, {})", g!(0), g!(1), g!(2)),
            "seq_add" => format!("({} \\o {})", g!(0), g!(1)),
            "seq_empty" => "<< >>".into(),
            "seq_last" => {
                let (v, s) = (g!(0), self.bind("s__"));
                format!("(LET {s} == {v} IN {s}[Len({s})])")
            }
            "seq_first" => format!("{}[1]", g!(0)),
            "seq_drop_first" => format!("Tail({})", g!(0)),
            "seq_drop_last" => {
                let (v, s) = (g!(0), self.bind("s__"));
                format!("(LET {s} == {v} IN SubSeq({s}, 1, Len({s}) - 1))")
            }
            "seq_take" => format!("SubSeq({}, 1, {})", g!(0), g!(1)),
            "seq_skip" => {
                let (v, n, s) = (g!(0), g!(1), self.bind("s__"));
                format!("(LET {s} == {v} IN SubSeq({s}, ({n}) + 1, Len({s})))")
            }
            "seq_contains" => {
                let (v, x) = (g!(0), g!(1));
                let (s, i) = (self.bind("s__"), self.bind("i__"));
                format!("(LET {s} == {v} IN \\E {i} \\in 1..Len({s}) : {s}[{i}] = {x})")
            }
            "seq_new" => match args.get(1).map(|a| peel(a)) {
                Some(f) => match &f.x {
                    ExprX::Closure(params, body) if params.len() == 1 => {
                        let len = g!(0);
                        let i = self.bind("i__");
                        let mut env2 = env.clone();
                        let n = self.bind_var(&mut env2, &params[0].name);
                        let b = self.expr(body, &env2);
                        format!("[{i} \\in 1..({len}) |-> LET {n} == {i} - 1 IN {b}]")
                    }
                    _ => self.refuse("Seq::new with a non-literal function", &e.span),
                },
                None => self.refuse("Seq::new with a non-literal function", &e.span),
            },
            "set_contains" => {
                let (s, x) = (g!(0), g!(1));
                format!("({x} \\in {s})")
            }
            "set_insert" => format!("({} \\cup {{{}}})", g!(0), g!(1)),
            "set_remove" => format!("({} \\ {{{}}})", g!(0), g!(1)),
            "set_empty" => "{}".into(),
            "set_union" => format!("({} \\cup {})", g!(0), g!(1)),
            "set_intersect" => format!("({} \\cap {})", g!(0), g!(1)),
            "set_difference" => format!("({} \\ {})", g!(0), g!(1)),
            "set_subset_of" => format!("({} \\subseteq {})", g!(0), g!(1)),
            "set_len" => format!("Cardinality({})", g!(0)),
            "set_finite" => format!("IsFiniteSet({})", g!(0)),
            "set_is_empty" => format!("({} = {{}})", g!(0)),
            "set_full" => self.refuse("Set::full (unbounded)", &e.span),
            "ext_equal" => format!("({} = {})", g!(0), g!(1)),
            "map_dom" => format!("DOMAIN {}", g!(0)),
            "map_index" => format!("{}[{}]", g!(0), g!(1)),
            "map_insert" => {
                let (m, k, v) = (g!(0), g!(1), g!(2));
                format!("(({k} :> {v}) @@ {m})")
            }
            "map_remove" => {
                let (v, k) = (g!(0), g!(1));
                let (m, x) = (self.bind("m__"), self.bind("k__"));
                format!("(LET {m} == {v} IN [{x} \\in (DOMAIN {m}) \\ {{{k}}} |-> {m}[{x}]])")
            }
            "map_empty" => {
                let x = self.bind("k__");
                format!("[{x} \\in {{}} |-> {x}]")
            }
            "map_contains_key" => {
                let (m, k) = (g!(0), g!(1));
                format!("({k} \\in DOMAIN {m})")
            }
            "map_len" => format!("Cardinality(DOMAIN {})", g!(0)),
            "map_values" => {
                let v = g!(0);
                let (m, x) = (self.bind("m__"), self.bind("k__"));
                format!("(LET {m} == {v} IN {{{m}[{x}] : {x} \\in DOMAIN {m}}})")
            }
            _ => self.refuse(format!("vstd operation {op}"), &e.span),
        }
    }

    // ─── quantifiers ────────────────────────────────────────────────────

    fn quant(
        &mut self,
        e: &Expr,
        q: &Quant,
        binders: &VarBinders<Typ>,
        body: &Expr,
        env: &Env,
    ) -> String {
        let forall = matches!(q.quant, air::ast::Quant::Forall);
        let mut env2 = env.clone();
        for b in binders.iter() {
            self.bind_var(&mut env2, &b.name);
        }
        // The guard: the antecedent of an implication (forall) or the
        // conjuncts (exists).
        // Explicit triggers wrap the body; the guard is underneath.
        let inner = peel(body);
        let guard_exprs: Vec<Expr> = match (&inner.x, forall) {
            (ExprX::Logical(LogicalOp::Implies, g, _), true) => conjuncts(g),
            (ExprX::Logical(LogicalOp::And, _, _), false) => conjuncts(&inner),
            _ => vec![],
        };
        let mut bounds = Vec::new();
        for (i, b) in binders.iter().enumerate() {
            let name = env2.name(&b.name);
            // A binder's domain may read the binders before it (the
            // quantifiers nest) but not itself or the ones after it.
            let unbound: Vec<VarIdent> = binders[i..].iter().map(|b| b.name.clone()).collect();
            let domain = match self
                .quiet(|x| x.bound_from_guard(&b.name, &b.a, &unbound, &guard_exprs, &env2))
            {
                Some(d) => d,
                None => match self.bound_from_type(&b.a, &e.span, &mut Vec::new()) {
                    Some(d) => d,
                    None => {
                        let constant = format!("Dom_{}", sanitize(&typ_name(&b.a)));
                        self.constants.insert(constant.clone());
                        self.holes.push(Hole {
                            variable: name.clone(),
                            typ: typ_name(&b.a),
                            constant: constant.clone(),
                            location: span_string(&e.span),
                            in_function: self.current.clone(),
                        });
                        constant
                    }
                },
            };
            bounds.push(format!("{name} \\in {domain}"));
        }
        let sb = if forall { self.expr(body, &env2) } else { self.in_branch(body, &env2) };
        let q = if forall { "\\A" } else { "\\E" };
        let mut out = sb;
        for bound in bounds.into_iter().rev() {
            out = format!("({q} {bound} : {out})");
        }
        out
    }

    /// A finite domain from the type alone: booleans, and enums whose
    /// variants' fields are themselves bounded (a variant's field of an
    /// unbounded type becomes a hole constant of its own).
    /// `seen` holds the datatypes being bounded, so a recursive datatype is
    /// a hole rather than an endless recursion.
    fn bound_from_type(
        &mut self,
        typ: &Typ,
        span: &crate::messages::Span,
        seen: &mut Vec<Path>,
    ) -> Option<String> {
        match &**typ {
            TypX::Bool => Some("BOOLEAN".into()),
            TypX::Datatype(Dt::Path(p), args, _) => {
                if seen.contains(p) {
                    return None;
                }
                let d = self.datatypes.get(p)?.clone();
                if d.x.typ_params.len() != args.len() {
                    return None;
                }
                // The constant for an unbounded field is named after the
                // instantiation (`Option_bool`, `Option_int`), since each
                // needs its own set.
                let instance = sanitize(&typ_name(typ));
                if d.x.variants.len() < 2 && d.x.variants.iter().all(|v| v.fields.is_empty()) {
                    return None;
                }
                let tagged = d.x.variants.len() > 1;
                let mut parts = Vec::new();
                for v in d.x.variants.iter() {
                    if v.name.to_string() == "dummy_to_use_type_params" {
                        continue;
                    }
                    let mut fields = Vec::new();
                    if tagged {
                        fields.push(format!("tag |-> \"{}\"", v.name));
                    }
                    let mut binds = Vec::new();
                    for f in v.fields.iter() {
                        let fname = field_name(&f.name);
                        let ftyp =
                            crate::sst_util::subst_typ_for_datatype(&d.x.typ_params, args, &f.a.0);
                        seen.push(p.clone());
                        let bounded = self.bound_from_type(&ftyp, span, seen);
                        seen.pop();
                        let domain = match bounded {
                            Some(dom) => dom,
                            None => {
                                let constant =
                                    format!("Dom_{instance}_{}_{}", sanitize(&v.name), fname);
                                self.constants.insert(constant.clone());
                                self.holes.push(Hole {
                                    variable: format!("{}.{}", v.name, fname),
                                    typ: typ_name(&ftyp),
                                    constant: constant.clone(),
                                    location: span_string(span),
                                    in_function: self.current.clone(),
                                });
                                constant
                            }
                        };
                        let x = self.bind(&format!("{fname}__"));
                        fields.push(format!("{fname} |-> {x}"));
                        binds.push(format!("{x} \\in {domain}"));
                    }
                    let record = format!("[{}]", fields.join(", "));
                    if binds.is_empty() {
                        parts.push(format!("{{{record}}}"));
                    } else {
                        parts.push(format!("{{{record} : {}}}", binds.join(", ")));
                    }
                }
                if parts.is_empty() { None } else { Some(format!("({})", parts.join(" \\cup "))) }
            }
            TypX::Decorate(_, _, t) | TypX::Boxed(t) => self.bound_from_type(t, span, seen),
            _ => None,
        }
    }

    /// A finite domain for `v` read off the guard's conjuncts: membership in
    /// a set, a map's domain, or an integer range from inequalities.
    /// The bound may not read `unbound` (the binder itself and the binders
    /// after it).
    fn bound_from_guard(
        &mut self,
        v: &VarIdent,
        typ: &Typ,
        unbound: &[VarIdent],
        guard: &[Expr],
        env: &Env,
    ) -> Option<String> {
        let is_v = |x: &Expr| read_var(x).as_ref() == Some(v);
        let free = |x: &Expr| !unbound.iter().any(|u| mentions(x, u));
        // Membership.
        for g in guard {
            if let ExprX::Call { target: CallTarget::Fun(_, fun, ..), args, .. } = &g.x {
                let name = fun_as_friendly_rust_name(fun);
                match vstd_op(&name) {
                    Some("set_contains") if args.len() == 2 && is_v(&args[1]) && free(&args[0]) => {
                        return Some(self.expr(&args[0], env));
                    }
                    Some("map_contains_key")
                        if args.len() == 2 && is_v(&args[1]) && free(&args[0]) =>
                    {
                        return Some(format!("DOMAIN {}", self.expr(&args[0], env)));
                    }
                    Some("seq_contains") if args.len() == 2 && is_v(&args[1]) && free(&args[0]) => {
                        let s = self.expr(&args[0], env);
                        let (sv, i) = (self.bind("s__"), self.bind("i__"));
                        return Some(format!(
                            "(LET {sv} == {s} IN {{{sv}[{i}] : {i} \\in 1..Len({sv})}})"
                        ));
                    }
                    _ => {}
                }
            }
        }
        // Integer range from inequalities and chained comparisons.
        let mut lower: Option<String> = None;
        let mut upper: Option<String> = None;
        let note = |side: &Expr,
                    op: InequalityOp,
                    other: &Expr,
                    this: &mut Self,
                    lower: &mut Option<String>,
                    upper: &mut Option<String>| {
            // side is v; the comparison is `v op other`.
            let _ = side;
            if !free(other) {
                return;
            }
            let o = this.expr(other, env);
            match op {
                InequalityOp::Ge => *lower = Some(o),
                InequalityOp::Gt => *lower = Some(format!("({o}) + 1")),
                InequalityOp::Le => *upper = Some(o),
                InequalityOp::Lt => *upper = Some(format!("({o}) - 1")),
            }
        };
        let flip = |op: &InequalityOp| match op {
            InequalityOp::Le => InequalityOp::Ge,
            InequalityOp::Ge => InequalityOp::Le,
            InequalityOp::Lt => InequalityOp::Gt,
            InequalityOp::Gt => InequalityOp::Lt,
        };
        for g in guard {
            match &g.x {
                ExprX::Binary(BinaryOp::Inequality(op), a, b) => {
                    if is_v(a) {
                        note(a, *op, b, self, &mut lower, &mut upper);
                    } else if is_v(b) {
                        note(b, flip(op), a, self, &mut lower, &mut upper);
                    }
                }
                ExprX::Multi(MultiOp::Chained(ops), args) => {
                    for (i, op) in ops.iter().enumerate() {
                        if let ChainedOp::Inequality(op) = op {
                            let (a, b) = (&args[i], &args[i + 1]);
                            if is_v(a) {
                                note(a, *op, b, self, &mut lower, &mut upper);
                            } else if is_v(b) {
                                note(b, flip(op), a, self, &mut lower, &mut upper);
                            }
                        }
                    }
                }
                _ => {}
            }
        }
        // A nat or unsigned binder is at least 0 whatever the guard says.
        let unsigned = matches!(
            &*crate::ast_util::undecorate_typ(typ),
            TypX::Int(IntRange::Nat | IntRange::U(_) | IntRange::USize)
        );
        if unsigned {
            lower = Some(match lower {
                Some(l) => format!("(IF ({l}) > 0 THEN ({l}) ELSE 0)"),
                None => "0".into(),
            });
        }
        match (lower, upper) {
            (Some(l), Some(u)) => Some(format!("{l}..{u}")),
            _ => None,
        }
    }

    // ─── functions ──────────────────────────────────────────────────────

    /// Print `e` as a branch: a transition it calls is one of its own.
    fn in_branch(&mut self, e: &Expr, env: &Env) -> String {
        self.branch_depth += 1;
        let s = self.expr(e, env);
        self.branch_depth -= 1;
        s
    }

    /// Keep what an operator's body assigns and calls, for
    /// [`Exporter::transitions`].
    fn record_body(&mut self, key: &OpKey) {
        let assigned = std::mem::take(&mut self.current_assigned);
        self.assigned.insert(key.clone(), assigned);
        self.calls.insert(key.clone(), std::mem::take(&mut self.current_calls));
    }

    /// `TypeOK`'s conjuncts: for each state variable whose type bounds its
    /// integers, the predicate keeping it in range, with its variable.
    fn type_ok(&mut self) -> Vec<(String, String)> {
        self.bound.clear();
        self.current = "TypeOK".into();
        let mut out = Vec::new();
        for (var, typ) in self.state_vars.clone().iter().zip(self.state_types.clone().iter()) {
            let mut seen = vec![self.state_path.clone()];
            if let Some(p) = self.type_pred(var, typ, &mut seen) {
                out.push((var.clone(), p));
            }
        }
        out
    }

    /// The predicate keeping `subject`, of type `typ`, in the type's range:
    /// every integer it holds, through records, enum payloads, tuples and
    /// `Seq`/`Set`/`Map` elements, within its integer type's bounds. `None`
    /// when the type bounds nothing. `seen` holds the datatypes being
    /// descended into, so a recursive datatype stops.
    fn type_pred(&mut self, subject: &str, typ: &Typ, seen: &mut Vec<Path>) -> Option<String> {
        let conj = |parts: Vec<String>| match parts.len() {
            0 => None,
            1 => parts.into_iter().next(),
            _ => Some(format!("({})", parts.join(" /\\ "))),
        };
        match &**typ {
            TypX::Int(range) => int_range_pred(subject, range),
            TypX::Decorate(_, _, t) | TypX::Boxed(t) => self.type_pred(subject, t, seen),
            TypX::Datatype(Dt::Tuple(_), args, _) => {
                let mut parts = Vec::new();
                for (i, a) in args.iter().enumerate() {
                    parts.extend(self.type_pred(&format!("{subject}[{}]", i + 1), a, seen));
                }
                conj(parts)
            }
            TypX::Datatype(Dt::Path(p), args, _) => match path_as_friendly_rust_name(p).as_str() {
                "vstd::seq::Seq" => {
                    let i = self.bind("i__");
                    let inner = self.type_pred(&format!("{subject}[{i}]"), args.first()?, seen)?;
                    Some(format!("(\\A {i} \\in 1..Len({subject}) : {inner})"))
                }
                "vstd::set::Set" => {
                    let x = self.bind("e__");
                    let inner = self.type_pred(&x, args.first()?, seen)?;
                    Some(format!("(\\A {x} \\in {subject} : {inner})"))
                }
                "vstd::map::Map" => {
                    let k = self.bind("k__");
                    let key = self.type_pred(&k, args.first()?, seen);
                    let value = self.type_pred(&format!("{subject}[{k}]"), args.get(1)?, seen);
                    let inner = conj(key.into_iter().chain(value).collect())?;
                    Some(format!("(\\A {k} \\in DOMAIN {subject} : {inner})"))
                }
                _ => {
                    if seen.contains(p) {
                        return None;
                    }
                    let d = self.datatypes.get(p)?.clone();
                    if d.x.typ_params.len() != args.len() {
                        return None;
                    }
                    let tagged = d.x.variants.len() > 1;
                    seen.push(p.clone());
                    let mut parts = Vec::new();
                    for v in d.x.variants.iter() {
                        if v.name.to_string() == "dummy_to_use_type_params" {
                            continue;
                        }
                        let mut fields = Vec::new();
                        for f in v.fields.iter() {
                            let ftyp = crate::sst_util::subst_typ_for_datatype(
                                &d.x.typ_params,
                                args,
                                &f.a.0,
                            );
                            let sub = format!("{subject}.{}", field_name(&f.name));
                            fields.extend(self.type_pred(&sub, &ftyp, seen));
                        }
                        match conj(fields) {
                            Some(c) if tagged => {
                                parts.push(format!("({subject}.tag = \"{}\" => {c})", v.name))
                            }
                            Some(c) => parts.push(c),
                            None => {}
                        }
                    }
                    seen.pop();
                    conj(parts)
                }
            },
            _ => None,
        }
    }

    /// The transitions Next reaches, each with the variables it leaves
    /// unassigned. A transition is Next itself, or an operator called at
    /// conjunct level in a branch of a transition or of an operator a
    /// transition conjoins. It assigns what it and the operators it conjoins
    /// (calls at conjunct level outside a branch) assign. One that only
    /// branches further and assigns nothing itself is not reported, since
    /// its branches are.
    fn transitions(&self, next: &OpKey) -> Vec<Transition> {
        let mut out = Vec::new();
        let mut seen: HashSet<OpKey> = HashSet::new();
        let mut queue = vec![next.clone()];
        while let Some(t) = queue.pop() {
            if !seen.insert(t.clone()) {
                continue;
            }
            // The operators `t` conjoins, `t` included.
            let mut conj: Vec<OpKey> = vec![t.clone()];
            let mut conj_seen: HashSet<OpKey> = HashSet::from([t.clone()]);
            let mut i = 0;
            let mut branches = false;
            while i < conj.len() {
                for (callee, reach) in self.calls.get(&conj[i]).into_iter().flatten() {
                    match reach {
                        Reach::Branch => {
                            branches = true;
                            queue.push(callee.clone());
                        }
                        Reach::Conjoined => {
                            if conj_seen.insert(callee.clone()) {
                                conj.push(callee.clone());
                            }
                        }
                        Reach::Other => {}
                    }
                }
                i += 1;
            }
            let assigned: BTreeSet<String> = conj
                .iter()
                .flat_map(|k| self.assigned.get(k).into_iter().flatten())
                .cloned()
                .collect();
            if branches && assigned.is_empty() {
                continue;
            }
            let unassigned =
                self.state_vars.iter().filter(|v| !assigned.contains(*v)).cloned().collect();
            let operator = self.op_names.get(&t).cloned().unwrap_or_default();
            out.push(Transition { operator, unassigned });
        }
        out.sort_by(|a, b| a.operator.cmp(&b.operator));
        out
    }

    /// The role of each parameter: a state-typed parameter is pre or post
    /// (the first one pre, a second one post), any other is None.
    fn param_roles(&self, f: &Function) -> Vec<Option<Role>> {
        let mut seen = 0;
        f.x.params
            .iter()
            .map(|p| {
                if self.is_state_typ(&p.x.typ) {
                    seen += 1;
                    Some(if seen == 1 { Role::Pre } else { Role::Post })
                } else {
                    None
                }
            })
            .collect()
    }

    /// Emit the operator for `key` (and, first, everything it calls) unless
    /// it is emitted or being emitted; return its name. A refusal it reaches
    /// taints the operator being printed.
    fn ensure_function(&mut self, key: &OpKey) -> String {
        let name = self.op_name(key);
        let reach = match (self.conj_level, self.branch_depth > 0) {
            (false, _) => Reach::Other,
            (true, true) => Reach::Branch,
            (true, false) => Reach::Conjoined,
        };
        self.current_calls.push((key.clone(), reach));
        if self.emitted.contains(key) || self.emitting.contains(key) {
            if self.tainted.contains(key) {
                self.current_tainted = true;
            }
            return name;
        }
        let (fun, primed) = key;
        let Some(f) = self.functions.get(fun).cloned() else { return name };
        self.emitting.insert(key.clone());
        let previous = std::mem::replace(&mut self.current, fun_as_friendly_rust_name(fun));
        let previous_bound = std::mem::take(&mut self.bound);
        let previous_tainted = std::mem::replace(&mut self.current_tainted, false);
        let previous_depth = std::mem::replace(&mut self.branch_depth, 0);
        let previous_calls = std::mem::take(&mut self.current_calls);
        let previous_assigned = std::mem::take(&mut self.current_assigned);
        let previous_enclosing = std::mem::take(&mut self.enclosing_assigned);
        let previous_level = std::mem::replace(&mut self.conj_level, true);
        let mut env = Env::new();
        let roles = self.param_roles(&f);
        let mut params = Vec::new();
        for (p, role) in f.x.params.iter().zip(roles.iter()) {
            match role {
                // The primed variant reads its one state parameter as post.
                Some(Role::Pre) if *primed => {
                    env.roles.insert(p.x.name.clone(), Role::Post);
                }
                Some(r) => {
                    env.roles.insert(p.x.name.clone(), *r);
                }
                None => {
                    let n = self.bind_var(&mut env, &p.x.name);
                    params.push(n);
                }
            }
        }
        let body = match &f.x.body {
            Some(b) => self.expr(b, &env),
            None => self.refuse("uninterpreted function", &f.span),
        };
        let head =
            if params.is_empty() { name.clone() } else { format!("{name}({})", params.join(", ")) };
        let mut def = String::new();
        def.push_str(&format!(
            "\\* {}{}, {}\n",
            fun_as_friendly_rust_name(fun),
            if *primed { " (read in the post state)" } else { "" },
            span_string(&f.span)
        ));
        if f.x.decrease.len() > 0 {
            self.recursive.insert(name.clone(), params.len());
        }
        def.push_str(&format!("{head} ==\n    {body}\n"));
        self.defs.push(def);
        self.record_body(key);
        self.current_calls = previous_calls;
        self.current_assigned = previous_assigned;
        self.enclosing_assigned = previous_enclosing;
        self.conj_level = previous_level;
        self.branch_depth = previous_depth;
        if self.current_tainted {
            self.tainted.insert(key.clone());
        }
        self.current = previous;
        self.bound = previous_bound;
        self.current_tainted = previous_tainted || self.tainted.contains(key);
        self.emitting.remove(key);
        self.emitted.insert(key.clone());
        name
    }
}

/// Whether a conjunct-level `e` keeps its conjunct-level children there: a
/// conjunction, a `LET` block, an `IF`, `match` or disjunction (whose arms
/// are, their conditions not), an equality (which assigns; its operands are
/// not at conjunct level), a reduced closure application, an `exists`, and
/// wrappers that print as their operand. Anything else (a negation, an
/// implication, a `forall`, a call's arguments, arithmetic) is not. A call
/// is conjunctive so its operator is recorded as called at conjunct level;
/// its arguments are not.
fn conjunctive(e: &Expr) -> bool {
    match &e.x {
        ExprX::Logical(LogicalOp::And | LogicalOp::Or, ..)
        | ExprX::Block(..)
        | ExprX::If(..)
        | ExprX::Match(..)
        | ExprX::Binary(BinaryOp::Eq(_), ..)
        | ExprX::BinaryOpr(BinaryOpr::ExtEq(..), ..)
        | ExprX::Call { target: CallTarget::FnSpec(_) | CallTarget::Fun(..), .. }
        | ExprX::WithTriggers { .. }
        | ExprX::ReadPlace(..)
        | ExprX::UnaryOpr(
            UnaryOpr::Box(_) | UnaryOpr::Unbox(_) | UnaryOpr::ProofNote(_) | UnaryOpr::CustomErr(_),
            _,
        )
        | ExprX::Unary(UnaryOp::Trigger(_) | UnaryOp::CoerceMode { .. }, _) => true,
        ExprX::Quant(q, ..) => matches!(q.quant, air::ast::Quant::Exists),
        _ => false,
    }
}

/// The predicate keeping the integer `s` in `range`, if the range bounds
/// it. TLC's integers are 32-bit, so a bound beyond them (`u32`'s upper,
/// `i32`'s and wider) is left out: TLC cannot reach it anyway, and
/// stops with an overflow first. A `char` is a string here.
fn int_range_pred(s: &str, range: &IntRange) -> Option<String> {
    match range {
        IntRange::Int | IntRange::Char | IntRange::ISize => None,
        IntRange::I(bits) if *bits >= 32 => None,
        IntRange::Nat | IntRange::USize => Some(format!("({s} >= 0)")),
        IntRange::U(bits) if *bits >= 31 => Some(format!("({s} >= 0)")),
        IntRange::U(bits) => Some(format!("(0 <= {s} /\\ {s} <= {})", (1u64 << bits) - 1)),
        IntRange::I(bits) => {
            let half = 1i64 << (bits - 1);
            Some(format!("({} <= {s} /\\ {s} <= {})", -half, half - 1))
        }
    }
}

/// Whether the literal `i` lies in `range`. `usize`/`isize` are taken at 32
/// bits, the narrowest width Verus allows, so a literal counted in range is
/// in range on every architecture; `char` is never.
fn int_in_range(i: &num_bigint::BigInt, range: &IntRange) -> bool {
    use num_bigint::BigInt;
    let signed = |bits: u32| {
        let half = BigInt::from(1) << (bits - 1);
        -half.clone() <= *i && *i < half
    };
    let unsigned = |bits: u32| BigInt::from(0) <= *i && *i < (BigInt::from(1) << bits);
    match range {
        IntRange::Int => true,
        IntRange::Nat => *i >= BigInt::from(0),
        IntRange::U(bits) => unsigned(*bits),
        IntRange::I(bits) => signed(*bits),
        IntRange::USize => unsigned(32),
        IntRange::ISize => signed(32),
        IntRange::Char => false,
    }
}

fn field_name(f: &Ident) -> String {
    let s = f.to_string();
    if s.chars().next().map(|c| c.is_ascii_digit()).unwrap_or(false) { format!("v{s}") } else { s }
}

fn expr_kind(x: &ExprX) -> &'static str {
    match x {
        ExprX::Loop { .. } => "loop",
        ExprX::Assign { .. } => "assignment",
        ExprX::NonSpecClosure { .. } => "exec closure",
        ExprX::ArrayLiteral(_) => "array literal",
        ExprX::ExecFnByName(_) => "function by name",
        ExprX::OpenInvariant(..) => "open invariant",
        ExprX::Return(_) => "return",
        ExprX::BreakOrContinue { .. } => "break/continue",
        ExprX::Ghost { .. } => "ghost block",
        _ => "unsupported",
    }
}

/// The recognised triple.
struct Triple {
    shape: &'static str,
    state: Path,
    init: Fun,
    next: Fun,
    /// Every candidate invariant: whether it is selected, and why.
    candidates: Vec<(Fun, bool, String)>,
    /// Whether the invariants were named on the command line.
    explicit: bool,
}

fn module_of(f: &Function) -> Option<Path> {
    f.x.owning_module.clone()
}

/// Split `-V tla-export`'s argument, `crate::a::b` or `crate::a::b:inv1,inv2`,
/// into the module and the invariants named after its single `:`.
pub fn parse_export_arg(arg: &str) -> Result<(String, Option<Vec<String>>), String> {
    let b = arg.as_bytes();
    let colon = (0..b.len()).find(|&i| {
        b[i] == b':' && (i == 0 || b[i - 1] != b':') && (i + 1 == b.len() || b[i + 1] != b':')
    });
    let Some(i) = colon else { return Ok((arg.to_string(), None)) };
    let module = arg[..i].to_string();
    let names: Vec<String> =
        arg[i + 1..].split(',').map(|n| n.trim().to_string()).filter(|n| !n.is_empty()).collect();
    if module.is_empty() || names.is_empty() {
        return Err(format!("`{arg}` is not `<module>` or `<module>:<invariant>,<invariant>,...`"));
    }
    let mut unique = Vec::new();
    for n in names {
        if !unique.contains(&n) {
            unique.push(n);
        }
    }
    Ok((module, Some(unique)))
}

/// Pick the invariants among `pool`: those named on the command line, or
/// else those `default` selects (with its reason for each).
fn select_invariants(
    pool: &[Function],
    named: Option<&[String]>,
    module: &str,
    default: impl Fn(&Function) -> (bool, String),
) -> Result<Vec<(Fun, bool, String)>, String> {
    let short = |f: &Function| last_segment(&f.x.name.path);
    let Some(named) = named else {
        return Ok(pool
            .iter()
            .map(|f| {
                let (selected, reason) = default(f);
                (f.x.name.clone(), selected, reason)
            })
            .collect());
    };
    for n in named {
        let found =
            pool.iter().any(|f| short(f) == *n || fun_as_friendly_rust_name(&f.x.name) == *n);
        if !found {
            return Err(format!(
                "no invariant `{n}` in `{module}`; the candidates are: {}",
                pool.iter().map(short).collect::<Vec<_>>().join(", ")
            ));
        }
    }
    Ok(pool
        .iter()
        .map(|f| {
            let chosen =
                named.iter().any(|n| short(f) == *n || fun_as_friendly_rust_name(&f.x.name) == *n);
            let reason =
                if chosen { "named on the command line" } else { "not named on the command line" };
            (f.x.name.clone(), chosen, reason.to_string())
        })
        .collect())
}

fn recognise(krate: &Krate, module: &str, named: Option<&[String]>) -> Result<Triple, String> {
    let in_module: Vec<Function> = krate
        .functions
        .iter()
        .filter(|f| module_of(f).map(|m| path_as_friendly_rust_name(&m) == module).unwrap_or(false))
        .cloned()
        .collect();
    if in_module.is_empty() {
        let known: BTreeSet<String> = krate
            .functions
            .iter()
            .filter_map(module_of)
            .map(|m| path_as_friendly_rust_name(&m))
            .collect();
        return Err(format!(
            "no functions in module `{module}`; modules with functions: {}",
            known.into_iter().collect::<Vec<_>>().join(", ")
        ));
    }
    let short = |f: &Function| last_segment(&f.x.name.path);
    let state_of = |f: &Function| f.x.params.first().and_then(|p| typ_datatype(&p.x.typ));
    let is_bool = |f: &Function| matches!(&*f.x.ret.x.typ, TypX::Bool);
    // Hand-rolled or VerusSync: `next(pre, post)` with two params of one datatype.
    let next = in_module.iter().find(|f| {
        short(f) == "next"
            && f.x.params.len() == 2
            && is_bool(f)
            && state_of(f).is_some()
            && state_of(f) == f.x.params.get(1).and_then(|p| typ_datatype(&p.x.typ))
    });
    if let Some(next) = next {
        let state = state_of(next).unwrap();
        let init = in_module
            .iter()
            .find(|f| {
                short(f) == "init"
                    && f.x.params.len() == 1
                    && is_bool(f)
                    && state_of(f).as_ref() == Some(&state)
            })
            .ok_or_else(|| {
                format!("found `next` in `{module}` but no `init(s: State) -> bool` beside it")
            })?;
        let shape = if in_module.iter().any(|f| short(f) == "next_by") {
            "verussync"
        } else {
            "hand-rolled"
        };
        // Every `(State) -> bool` spec fn with a body, other than `init`.
        let pool: Vec<Function> = in_module
            .iter()
            .filter(|f| {
                f.x.params.len() == 1
                    && is_bool(f)
                    && state_of(f).as_ref() == Some(&state)
                    && short(f) != "init"
                    && f.x.mode == Mode::Spec
                    && f.x.body.is_some()
            })
            .cloned()
            .collect();
        let candidates = if shape == "verussync" {
            // `state_machine!` generates `State::invariant(&self)` as the
            // conjunction `self.a() && self.b() && ...` of the `#[invariant]`
            // methods (or `true` when there are none); those are the
            // invariants. The generated `<transition>_enabled` predicates and
            // any helper are not.
            let conj = pool.iter().find(|f| short(f) == "invariant");
            let mut invs: Vec<Fun> = Vec::new();
            let mut whole = false;
            if let Some(conj) = conj {
                let param = conj.x.params[0].x.name.clone();
                for c in conjuncts(conj.x.body.as_ref().unwrap()) {
                    match &c.x {
                        ExprX::Const(Constant::Bool(true)) => {}
                        ExprX::Call { target: CallTarget::Fun(_, fun, ..), args, .. }
                            if args.len() == 1
                                && read_var(&args[0]).as_ref() == Some(&param)
                                && pool.iter().any(|f| f.x.name == *fun) =>
                        {
                            invs.push(fun.clone())
                        }
                        // Not the generated shape: check the conjunction whole.
                        _ => whole = true,
                    }
                }
            }
            select_invariants(&pool, named, module, |f| {
                if short(f) == "invariant" {
                    if whole {
                        (true, "State::invariant, checked whole: a conjunct is not a call to an #[invariant] method".into())
                    } else {
                        (false, "the conjunction of the #[invariant] methods, which are checked one by one".into())
                    }
                } else if !whole && invs.contains(&f.x.name) {
                    (
                        true,
                        "an #[invariant] of the state machine (a conjunct of State::invariant)"
                            .into(),
                    )
                } else {
                    (false, "not an #[invariant] of the state machine (a generated or helper predicate)".into())
                }
            })?
        } else {
            // One named `invariant` is checked like any other, even when it
            // conjoins the rest: leaving it out could leave nothing checked.
            select_invariants(&pool, named, module, |_| {
                (true, "a (State) -> bool spec fn in the module".into())
            })?
        };
        return Ok(Triple {
            shape,
            state,
            init: init.x.name.clone(),
            next: next.x.name.clone(),
            candidates,
            explicit: named.is_some(),
        });
    }
    // verus-tla: `next()` returning a spec_fn over (S, S).
    let next = in_module.iter().find(|f| short(f) == "next" && f.x.params.is_empty() && matches!(&*f.x.ret.x.typ, TypX::SpecFn(ps, r) if ps.len() == 2 && matches!(&**r, TypX::Bool)));
    if let Some(next) = next {
        let state = match &*next.x.ret.x.typ {
            TypX::SpecFn(ps, _) => {
                typ_datatype(&ps[0]).ok_or("state type of `next()` is not a datatype")?
            }
            _ => unreachable!(),
        };
        let init = in_module
            .iter()
            .find(|f| {
                short(f) == "init"
                    && f.x.params.is_empty()
                    && matches!(&*f.x.ret.x.typ, TypX::SpecFn(ps, _) if ps.len() == 1)
            })
            .ok_or("found verus-tla `next()` but no `init()`")?;
        let pool: Vec<Function> = in_module
            .iter()
            .filter(|f| f.x.params.is_empty() && matches!(&*f.x.ret.x.typ, TypX::SpecFn(ps, r) if ps.len() == 1 && matches!(&**r, TypX::Bool)) && short(f) != "init")
            .cloned()
            .collect();
        let candidates = select_invariants(&pool, named, module, |_| {
            (true, "a verus-tla closure over the state returning bool".into())
        })?;
        return Ok(Triple {
            shape: "verus-tla",
            state,
            init: init.x.name.clone(),
            next: next.x.name.clone(),
            candidates,
            explicit: named.is_some(),
        });
    }
    Err(format!(
        "no transition system found in `{module}`: expected `next(pre, post) -> bool` and `init(s) -> bool`, or verus-tla's `next()`/`init()` closures"
    ))
}

/// Export the transition system named by `arg`, `-V tla-export`'s argument:
/// a module (a `crate::a::b` path as Verus prints it), optionally followed by
/// `:inv1,inv2` naming the invariants to check.
pub fn export_module(krate: &Krate, arg: &str) -> Result<Export, String> {
    let (module, named) = parse_export_arg(arg)?;
    let module = module.as_str();
    let triple = recognise(krate, module, named.as_deref())?;
    let datatypes: HashMap<Path, Datatype> = krate
        .datatypes
        .iter()
        .filter_map(|d| match &d.x.name {
            Dt::Path(p) => Some((p.clone(), d.clone())),
            Dt::Tuple(_) => None,
        })
        .collect();
    let functions: HashMap<Fun, Function> =
        krate.functions.iter().map(|f| (f.x.name.clone(), f.clone())).collect();
    let state_dt = datatypes.get(&triple.state).ok_or("state datatype not found")?.clone();
    let state_fields: Vec<String> = state_dt
        .x
        .variants
        .first()
        .map(|v| v.fields.iter().map(|f| field_name(&f.name)).collect())
        .unwrap_or_default();
    if state_dt.x.variants.len() != 1 {
        return Err("the state type must be a struct".into());
    }
    let state_types: Vec<Typ> =
        state_dt.x.variants[0].fields.iter().map(|f| f.a.0.clone()).collect();
    let module_name = format!("{}_tla", sanitize(&last_segment(&triple.state)));
    // Each field is held in a variable of its own name, unless that name is
    // one the module generates (`vars`, `Init`, ...), the module's own name,
    // or reserved by TLA+: then the variable is renamed and the record label
    // kept.
    let mut state_vars: Vec<String> = Vec::new();
    for f in &state_fields {
        let clashes = |c: &str, taken: &[String]| {
            GENERATED_NAMES.contains(&c)
                || c == module_name
                || is_tla_reserved(c)
                || taken.iter().any(|t| t == c)
                || state_fields.iter().any(|g| g == c && g != f)
        };
        let mut v = f.clone();
        let mut n = 1;
        while clashes(&v, &state_vars) {
            v = if n == 1 { format!("{f}_v") } else { format!("{f}_v{n}") };
            n += 1;
        }
        state_vars.push(v);
    }
    let mut ex = Exporter {
        datatypes,
        functions,
        state_path: triple.state.clone(),
        state_fields: state_fields.clone(),
        state_vars: state_vars.clone(),
        uses_euclid: false,
        defs: Vec::new(),
        emitted: HashSet::new(),
        emitting: HashSet::new(),
        recursive: BTreeMap::new(),
        op_names: HashMap::new(),
        used_names: HashSet::new(),
        locals_ever: HashSet::new(),
        bound: HashSet::new(),
        tainted: HashSet::new(),
        current_tainted: false,
        branch_depth: 0,
        conj_level: false,
        calls: HashMap::new(),
        current_calls: Vec::new(),
        assigned: HashMap::new(),
        current_assigned: BTreeSet::new(),
        enclosing_assigned: Vec::new(),
        state_types,
        holes: Vec::new(),
        refusals: Vec::new(),
        constants: BTreeSet::new(),
        current: String::new(),
    };
    for v in &state_vars {
        ex.used_names.insert(v.clone());
    }
    for reserved in GENERATED_NAMES.iter().copied().chain([module_name.as_str()]) {
        ex.used_names.insert(reserved.into());
    }
    let selected: Vec<Fun> =
        triple.candidates.iter().filter(|(_, s, _)| *s).map(|(f, _, _)| f.clone()).collect();
    // What became of each candidate, when not what recognition decided.
    let mut outcome: HashMap<Fun, (bool, String)> = HashMap::new();
    let mut roots = vec![triple.init.clone(), triple.next.clone()];
    roots.extend(selected.iter().cloned());
    // verus-tla: the closures are the bodies; emit as state operators by
    // treating `init()`/`next()` specially.
    let verus_tla = triple.shape == "verus-tla";
    let mut init_name = String::new();
    let mut next_name = String::new();
    // Each invariant, and whether it reaches a refusal.
    let mut invs: Vec<(Fun, String, bool)> = Vec::new();
    if verus_tla {
        for (i, r) in roots.iter().enumerate() {
            let f = ex.functions.get(r).cloned().ok_or("root missing")?;
            let key = (r.clone(), false);
            let name = ex.op_name(&key);
            ex.current = fun_as_friendly_rust_name(r);
            ex.bound.clear();
            ex.current_tainted = false;
            ex.branch_depth = 0;
            ex.current_calls.clear();
            ex.current_assigned.clear();
            ex.enclosing_assigned.clear();
            ex.conj_level = true;
            let body = match &f.x.body {
                Some(b) => match &peel(b).x {
                    ExprX::Closure(params, body) => {
                        let mut env = Env::new();
                        for (k, p) in params.iter().enumerate() {
                            env.roles.insert(
                                p.name.clone(),
                                if k == 0 { Role::Pre } else { Role::Post },
                            );
                        }
                        ex.expr(body, &env)
                    }
                    _ => ex.refuse("verus-tla root whose body is not a closure literal", &b.span),
                },
                None => ex.refuse("root without a body", &f.span),
            };
            ex.defs.push(format!(
                "\\* {}, {}\n{name} ==\n    {body}\n",
                fun_as_friendly_rust_name(r),
                span_string(&f.span)
            ));
            ex.record_body(&key);
            ex.emitted.insert(key.clone());
            if ex.current_tainted {
                ex.tainted.insert(key);
            }
            match i {
                0 => init_name = name,
                1 => next_name = name,
                _ => invs.push((r.clone(), name, ex.current_tainted)),
            }
        }
    } else {
        init_name = ex.ensure_function(&(triple.init.clone(), false));
        next_name = ex.ensure_function(&(triple.next.clone(), false));
        // A predicate init or next reads unprimed is a guard or helper of
        // the transition, not an invariant, unless the command line names
        // it; it is reported as excluded, never dropped silently.
        let transitions: HashSet<OpKey> = ex.emitted.clone();
        for r in &selected {
            let key = (r.clone(), false);
            if !triple.explicit && transitions.contains(&key) {
                outcome.insert(
                    r.clone(),
                    (
                        false,
                        format!(
                            "reached from init/next unprimed (a guard or helper of the transition), so not taken as an invariant; name it in -V tla-export={module}:<invariants> to check it"
                        ),
                    ),
                );
                continue;
            }
            let name = ex.ensure_function(&key);
            invs.push((r.clone(), name, ex.tainted.contains(&key)));
        }
    }
    for (f, _, tainted) in &invs {
        if *tainted {
            outcome.insert(
                f.clone(),
                (false, "reaches a refusal, so it is left out of the .cfg (see refusals)".into()),
            );
        }
    }
    let transitions = ex.transitions(&(triple.next.clone(), false));
    // Verus's state is always within its fields' types, so a step that
    // would leave them is disabled: TypeOK holds initially and after each
    // step.
    let type_ok = ex.type_ok();
    let inv_names: Vec<String> =
        invs.iter().filter(|(_, _, tainted)| !tainted).map(|(_, n, _)| n.clone()).collect();
    let skipped: Vec<String> =
        invs.iter().filter(|(_, _, tainted)| *tainted).map(|(_, n, _)| n.clone()).collect();
    let candidates: Vec<Candidate> = triple
        .candidates
        .iter()
        .map(|(f, selected, reason)| {
            let (included, reason) =
                outcome.get(f).cloned().unwrap_or_else(|| (*selected, reason.clone()));
            Candidate {
                function: fun_as_friendly_rust_name(f),
                operator: ex.op_names.get(&(f.clone(), false)).cloned(),
                included,
                reason,
            }
        })
        .collect();
    let mut tla = String::new();
    tla.push_str(&format!("---- MODULE {module_name} ----\n"));
    tla.push_str("\\* Exported by verus -V tla-export from the Verus model in `");
    tla.push_str(module);
    tla.push_str("`.\n\\* Mapping: structs are records; enum values are records with a `tag`;\n");
    tla.push_str("\\* Seq is a 1-based sequence (every index shifted once); Set is a set;\n");
    tla.push_str(
        "\\* Map is a function (dom = DOMAIN, insert = :> @@); Option is a record tagged\n",
    );
    tla.push_str(
        "\\* None/Some with field v0; nat/int/uN are Int, and TypeOK keeps each variable\n",
    );
    tla.push_str(
        "\\* in its type's range (conjoined to Init, primed to Next); a spec fn is an operator, its\n",
    );
    tla.push_str(
        "\\* pre/post state parameters dropped and read as the unprimed/primed variables;\n",
    );
    tla.push_str("\\* a quantifier is bounded from its guard, or from a CONSTANT Dom_<Type>.\n");
    tla.push_str(
        "\\* What the export could not express is an Assert(FALSE, ...) that stops TLC\n\\* wherever it is evaluated.\n",
    );
    tla.push_str("EXTENDS Integers, Sequences, FiniteSets, TLC\n\n");
    if !ex.constants.is_empty() {
        tla.push_str(&format!(
            "CONSTANTS {}\n\n",
            ex.constants.iter().cloned().collect::<Vec<_>>().join(", ")
        ));
    }
    tla.push_str(&format!("VARIABLES {}\n", state_vars.join(", ")));
    tla.push_str(&format!("vars == <<{}>>\n\n", state_vars.join(", ")));
    let renamed: Vec<String> = state_fields
        .iter()
        .zip(state_vars.iter())
        .filter(|(f, v)| f != v)
        .map(|(f, v)| format!("{f} in {v}"))
        .collect();
    if !renamed.is_empty() {
        tla.push_str(&format!(
            "\\* Fields held in a renamed variable (the name is taken): {}\n\n",
            renamed.join(", ")
        ));
    }
    if ex.uses_euclid {
        // Verus's `/` and `%` are Euclidean: the remainder is never negative.
        let (a, b) = (EUCLID_A, EUCLID_B);
        tla.push_str(&format!(
            "{EUCLID_MOD}({a}, {b}) == {a} % (IF {b} < 0 THEN -{b} ELSE {b})\n{EUCLID_DIV}({a}, {b}) == ({a} - {EUCLID_MOD}({a}, {b})) \\div {b}\n\n"
        ));
    }
    if !ex.recursive.is_empty() {
        for (r, arity) in &ex.recursive {
            if *arity == 0 {
                tla.push_str(&format!("RECURSIVE {r}\n"));
            } else {
                tla.push_str(&format!("RECURSIVE {r}({})\n", vec!["_"; *arity].join(", ")));
            }
        }
        tla.push('\n');
    }
    for d in &ex.defs {
        tla.push_str(d);
        tla.push('\n');
    }
    if type_ok.is_empty() {
        tla.push_str(&format!("Init == {init_name}\n"));
        tla.push_str(&format!("Next == {next_name}\n"));
    } else {
        tla.push_str(
            "\\* The state's integer fields stay within their types, as in Verus.\nTypeOK ==\n",
        );
        for (_, p) in &type_ok {
            tla.push_str(&format!("    /\\ {p}\n"));
        }
        tla.push_str(&format!("Init == {init_name} /\\ TypeOK\n"));
        tla.push_str(&format!("Next == {next_name} /\\ TypeOK'\n"));
    }
    tla.push_str("Spec == Init /\\ [][Next]_vars\n");
    if !inv_names.is_empty() {
        tla.push_str(&format!(
            "Inv == {}\n",
            inv_names.iter().map(|n| format!("({n})")).collect::<Vec<_>>().join(" /\\ ")
        ));
    }
    tla.push_str(&format!("{}\n", "=".repeat(module_name.len() + 20)));

    let mut cfg = String::new();
    cfg.push_str("SPECIFICATION Spec\n");
    if !inv_names.is_empty() {
        cfg.push_str("INVARIANTS\n");
        for n in &inv_names {
            cfg.push_str(&format!("  {n}\n"));
        }
    }
    for n in &skipped {
        cfg.push_str(&format!(
            "\\* INVARIANT {n} is left out: it reaches a refusal (see the .tla.json report)\n"
        ));
    }
    for c in candidates.iter().filter(|c| !c.included && c.reason.starts_with("reached from")) {
        cfg.push_str(&format!(
            "\\* {} is not checked: init/next read it unprimed (see the .tla.json candidates)\n",
            c.function
        ));
    }
    if inv_names.is_empty() {
        // Never silent: TLC with no invariant reports "No error has been found".
        if candidates.is_empty() {
            cfg.push_str("\\* No invariant is checked: the module has no candidate invariant.\n");
        } else {
            cfg.push_str(
                "\\* No invariant is checked. The candidates (see the .tla.json report):\n",
            );
            for c in &candidates {
                cfg.push_str(&format!("\\*   {}: {}\n", c.function, c.reason));
            }
        }
    }
    if !ex.constants.is_empty() {
        // Left unassigned on purpose: TLC stops until each is given a finite
        // set, rather than quantifying over an empty one.
        cfg.push_str(
            "\\* Domains the export could not bound. TLC stops until each is given a finite\n\\* set: uncomment the block and fill them in.\n\\* CONSTANTS\n",
        );
        for c in &ex.constants {
            cfg.push_str(&format!("\\*   {c} = {{ ... }}\n"));
        }
    }
    for t in transitions.iter().filter(|t| !t.unassigned.is_empty()) {
        cfg.push_str(&format!(
            "\\* Transition {} never assigns {}: TLC stops there with \"successor state not\n\\* completely specified\" (see the .tla.json transitions)\n",
            t.operator,
            t.unassigned.join(", ")
        ));
    }
    cfg.push_str(
        "\\* The unassigned check counts a conjunct-level v' = e (an IF, match or disjunction\n\\* when every branch assigns v). It can miss a v' read before the conjunct that\n\\* assigns it (TLC evaluates conjuncts in order) and does not count v' \\in S.\n",
    );
    cfg.push_str("\\* CONSTRAINT <a state predicate bounding the model>\n");
    let report = Report {
        module: module.to_string(),
        shape: triple.shape.to_string(),
        state_type: path_as_friendly_rust_name(&triple.state),
        variables: state_vars,
        typed_variables: type_ok.iter().map(|(v, _)| v.clone()).collect(),
        init: init_name,
        next: next_name,
        invariants: inv_names,
        transitions,
        skipped_invariants: skipped,
        candidates,
        operators: ex.defs.len(),
        holes: ex.holes,
        refusals: ex.refusals,
    };
    Ok(Export { module_name, tla, cfg, report })
}
